"""Adversary diagnostic (post hoc): how recoverable the planted-window statistics are.

For each model, features from experiments/score_adversary_probe.py are probed with
child-grouped five-fold ridge regression (inner grouped three-fold search for the penalty) for
each of four tracking statistics, giving an out-of-fold R^2. Per mechanism and world, R^2 of
the adversarial head and the no-remedy reference are averaged over three seeds and differenced,
with the range over the 3 x 3 seed pairs. This measures recoverability, not classifier use.
Writes results/v12/analysis/adversary_probe.csv and paper/tables/adversary_probe.tex.
"""
import csv
import itertools
import json
import os
import sys

import numpy as np
from sklearn.linear_model import Ridge
from sklearn.model_selection import GroupKFold

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

SRC = "results/posthoc/adversary_probe"
OUT = "results/v12/analysis/adversary_probe.csv"
TEX = "paper/tables/adversary_probe.tex"
ALPHAS = np.logspace(-1, 4, 11)
STATS = ("low_conf", "missing", "frozen", "arm_low_conf")
LABEL = {"low_conf": "low confidence", "missing": "missing", "frozen": "frozen frames", "arm_low_conf": "arm low conf."}
MECH = {"runs": "missing runs", "frozen": "frozen frames"}


def fit_predict(Xtr, ytr, Xte, gtr):
    mu, sd = Xtr.mean(0), Xtr.std(0) + 1e-6
    Xtr, Xte = (Xtr - mu) / sd, (Xte - mu) / sd
    best, err = None, np.inf
    for a in ALPHAS:
        e = []
        for itr, iva in GroupKFold(3).split(Xtr, ytr, gtr):
            e.append(((Ridge(alpha=a).fit(Xtr[itr], ytr[itr]).predict(Xtr[iva]) - ytr[iva]) ** 2).mean())
        if np.mean(e) < err:
            best, err = a, np.mean(e)
    return Ridge(alpha=best).fit(Xtr, ytr).predict(Xte)


def oof_r2(X, y, groups):
    if y.std() < 1e-9:
        return float("nan")
    pred = np.empty_like(y)
    for tr, te in GroupKFold(5).split(X, y, groups):
        pred[te] = fit_predict(X[tr], y[tr], X[te], groups[tr])
    return float(1 - ((pred - y) ** 2).sum() / ((y - y.mean()) ** 2).sum())


def main():
    reg = json.load(open(f"{SRC}/registry.json"))["models"]
    assert len(reg) == 24, len(reg)
    r2 = {}
    for m in reg:
        z = np.load(f"{SRC}/{m['name']}.npz")
        g = z["child_id"]
        r2[m["name"]] = [oof_r2(z["features"].astype(float), z["stats"][:, k].astype(float), g) for k in range(4)]
        print(m["name"], " ".join(f"{v:.3f}" for v in r2[m["name"]]), flush=True)
    rows = []
    for mech in ("runs", "frozen"):
        for world in ("S", "I"):
            adv = [m["name"] for m in reg if m["mechanism"] == mech and m["world"] == world and m["cell"] == "C_adversarial"]
            ref = [m["name"] for m in reg if m["mechanism"] == mech and m["world"] == world and m["cell"] == "A_none"]
            assert len(adv) == 3 and len(ref) == 3
            for k, st in enumerate(STATS):
                a = np.array([r2[n][k] for n in adv]); b = np.array([r2[n][k] for n in ref])
                diffs = [x - y for x, y in itertools.product(a, b)]
                rows.append({"mechanism": mech, "world": world, "statistic": st,
                             "r2_adversarial": f"{np.nanmean(a):.3f}", "r2_no_remedy": f"{np.nanmean(b):.3f}",
                             "difference": f"{np.nanmean(a) - np.nanmean(b):+.3f}",
                             "difference_range_seed_pairs": f"[{np.nanmin(diffs):+.3f}, {np.nanmax(diffs):+.3f}]"})
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", newline="") as f:
        f.write("# post hoc: out-of-fold R^2 of identifier-grouped ridge probes of the four "
                "window statistics from the 136-d pooled features, host test, own-world policy, first mask\n")
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    L = [r"\begin{tabular}{lllccc}", r"\toprule",
         r"Mechanism & World & Statistic & $R^2$, adversarial head & $R^2$, no remedy & Difference [range over seed pairs] \\",
         r"\midrule"]
    prev = None
    for r in rows:
        head = (r["mechanism"], r["world"])
        mlab = MECH[r["mechanism"]] if head != prev and (prev is None or prev[0] != r["mechanism"]) else ""
        wlab = r["world"] if head != prev else ""
        L.append(f"{mlab} & {wlab} & {LABEL[r['statistic']]} & {r['r2_adversarial']} & {r['r2_no_remedy']} & "
                 f"{r['difference']} {r['difference_range_seed_pairs']} \\\\".replace("-", "$-$"))
        prev = head
    L += [r"\bottomrule", r"\end{tabular}"]
    os.makedirs(os.path.dirname(TEX), exist_ok=True)
    with open(TEX, "w") as f:
        f.write("% generated by experiments/analyze_adversary_probe.py from results/posthoc/adversary_probe; do not edit\n")
        f.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
