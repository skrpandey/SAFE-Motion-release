"""Holm multiplicity sensitivity for the two declared contrast families (post hoc).

p-values come from inverting the paired identifier-clustered bootstrap of each contrast
(B = 2000, add-one form, floor 2/2001; the p_inv and raw_p_inv columns written by
analyze_v7_masks.py and analyze_v12.py), so "95% interval excludes zero" matches p < 0.05.
Families: the eight input-configuration contrasts (v7, v8) and the six cue-targeted remedy
contrasts (v12); Holm is applied within each family and scale (logit, raw AUROC) separately.
Writes results/v7/analysis/holm_v7.csv, results/v12/analysis/holm_v12.csv and
paper/tables/{holm_v7,holm_v12}.tex.
"""
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from safe_motion.paths import guard_output   # noqa: E402

MECH = {"runs": "missing runs", "whole": "whole-joint absence", "frozen": "frozen frames", "armruns": "arm confidence"}
CELL = {"A_velocity": "velocity", "A_dropout": "whole-joint dropout", "A_both": "velocity + dropout",
        "B_coorddrop": "coordinate dropout", "C_groupdro": "Group DRO", "C_adversarial": "adversarial head",
        "C_augment": "operator augmentation"}


def holm(ps):
    """Holm step-down adjusted p-values (monotone), same order as the input."""
    m = len(ps)
    order = sorted(range(m), key=lambda i: ps[i])
    adj, running = [0.0] * m, 0.0
    for rank, i in enumerate(order):
        running = max(running, min(1.0, (m - rank) * ps[i]))
        adj[i] = running
    return adj


def read(path):
    return list(csv.DictReader(l for l in open(path) if not l.startswith("#")))


def family_v7():
    rows = [r for r in read("results/v7/analysis/effects_masks.csv")
            if r["strength"] == "mid" and " - SE(A_none)" in r["contrast"] and r["contrast"].startswith("SE(") and "mid" not in r["contrast"]]
    out = []
    for r in rows:
        cell = r["contrast"][3:].split(")")[0]
        out.append({"family": "input configurations (8)", "mechanism": r["mechanism"], "cell": cell,
                    "logit": f"{float(r['point']):+.3f} [{float(r['ci_lo']):+.3f}, {float(r['ci_hi']):+.3f}]",
                    "raw": f"{float(r['raw_point']):+.3f} [{float(r['raw_ci_lo']):+.3f}, {float(r['raw_ci_hi']):+.3f}]",
                    "p_logit": float(r["p_inv"]), "p_raw": float(r["raw_p_inv"])})
    assert len(out) == 8, len(out)
    return out


def family_v12():
    rows = [r for r in read("results/v12/analysis/effects.csv") if " - SE(A_none)" in r["contrast"] and r["contrast"].startswith("SE(")]
    out = []
    for r in rows:
        cell = r["contrast"][3:].split(")")[0]
        out.append({"family": "remedies aimed at the cue (6)", "mechanism": r["mechanism"], "cell": cell,
                    "logit": r["logit"], "raw": r["raw"], "p_logit": float(r["p_inv"]), "p_raw": float(r["raw_p_inv"]),
                    "nominal_lowers": r.get("lowers_SE_P12_1", "")})
    assert len(out) == 6, len(out)
    return out


def finish(rows):
    for scale in ("logit", "raw"):
        adj = holm([r[f"p_{scale}"] for r in rows])
        for r, a in zip(rows, adj):
            r[f"p_{scale}_holm"] = a
    for r in rows:
        r["nominal_excludes_zero_logit"] = r["p_logit"] < 0.05
        r["nominal_excludes_zero_raw"] = r["p_raw"] < 0.05
        r["holm_excludes_zero_logit"] = r["p_logit_holm"] < 0.05
        r["holm_excludes_zero_raw"] = r["p_raw_holm"] < 0.05
        r["holm_both_scales"] = r["holm_excludes_zero_logit"] and r["holm_excludes_zero_raw"]
    return rows


def fmt_p(p):
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def table(rows, path, label):
    L = [f"% generated by experiments/holm_families.py from the p_inv columns of the analysis files; post hoc; do not edit",
         r"\begin{tabular}{llcccccc}", r"\toprule",
         r"Mechanism & Contrast & $\Delta$MWI (logit) & $p$ & Holm $p$ & $\Delta$MWI (raw) & $p$ & Holm $p$ \\", r"\midrule"]
    for r in rows:
        lg = r["logit"].replace("-", "$-$"); rw = r["raw"].replace("-", "$-$")
        L.append(f"{MECH[r['mechanism']]} & {CELL.get(r['cell'], r['cell'])} $-$ none & {lg} & {fmt_p(r['p_logit'])} & {fmt_p(r['p_logit_holm'])} & "
                 f"{rw} & {fmt_p(r['p_raw'])} & {fmt_p(r['p_raw_holm'])} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    guard_output(path)
    open(path, "w").write("\n".join(L) + "\n")
    print("wrote", path, f"({label}: {sum(r['holm_excludes_zero_logit'] for r in rows)} of {len(rows)} logit contrasts exclude zero after Holm, "
          f"{sum(r['holm_both_scales'] for r in rows)} on both scales)")


def write_csv(rows, path, note):
    guard_output(path)
    with open(path, "w", newline="") as f:
        f.write(f"# {note}\n")
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)


def main():
    note = ("post hoc multiplicity sensitivity: p by percentile-interval inversion of the paired "
            "cluster bootstrap, conditional on fitted models and masks; Holm within the family and scale")
    v7 = finish(family_v7()); write_csv(v7, "results/v7/analysis/holm_v7.csv", note); table(v7, "paper/tables/holm_v7.tex", "v7/v8 inputs")
    v12 = finish(family_v12()); write_csv(v12, "results/v12/analysis/holm_v12.csv", note); table(v12, "paper/tables/holm_v12.tex", "v12 remedies")


if __name__ == "__main__":
    main()
