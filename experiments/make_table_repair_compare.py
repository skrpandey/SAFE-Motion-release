"""Supplement table (protocol repair_selection_v14) of the reported quantities moved by the
selection repair: historical value, rerun under the original rule, rerun under the cleaned rule.
Exits non-zero if an original-rule rerun differs from the historical value, or if a cleaned
value equals the historical one at printed precision.
Usage: python experiments/make_table_repair_compare.py --orig build/release_v14_orig \
           --clean build/release_v14_clean --out paper/tables/repair_v14.tex"""
import argparse, csv, re, sys

ap = argparse.ArgumentParser()
ap.add_argument("--hist", default=".")
ap.add_argument("--orig", required=True)
ap.add_argument("--clean", required=True)
ap.add_argument("--out", default="paper/tables/repair_v14.tex")
a = ap.parse_args()


def rows(root, rel):
    return list(csv.DictReader(l for l in open(f"{root}/{rel}") if not l.startswith("#")))


def one(rs, **kw):
    hit = [r for r in rs if all(r[k] == v for k, v in kw.items())]
    assert len(hit) == 1, (kw, len(hit))
    return hit[0]


def iv(s):
    """'+0.0600 [-0.0021, +0.1175]' or '(-0.05, 0.09)' -> (point or None, lo, hi)."""
    v = [float(x) for x in re.findall(r"[+-]?\d+\.\d+", s)]
    return (v[0], v[1], v[2]) if len(v) == 3 else (None, v[0], v[1])


EFF = "results/v7/analysis/effects_masks.csv"


def effect(proto, mech, strength, contrast, field="point"):
    def get(root):
        r = one(rows(root, EFF), proto=proto, mechanism=mech, strength=strength, contrast=contrast)
        if field == "R_I":
            return iv(r["R_I_ci"])
        return float(r["point"]), float(r["ci_lo"]), float(r["ci_hi"])
    return get


def blind_whole(root):
    r = [x for x in rows(root, "results/v10/analysis/blind.csv")
         if x["mechanism"] == "whole" and x["contrast"].startswith("SE(A_none) - SE(A_blind)")]
    assert len(r) == 1
    return float(r[0]["point"]), None, None


def adv(field):
    def get(root):
        r = one(rows(root, "results/v12/analysis/effects.csv"), mechanism="frozen", cell="C_adversarial",
                contrast="SE(C_adversarial) - SE(A_none)")
        return iv(r[field])
    return get


def adv_crossed(root):
    r = one(rows(root, "results/v12/analysis/variance_v12.csv"), mechanism="frozen", cell="C_adversarial",
            quantity="Delta SE vs A_none")
    return iv(r["crossed_ci"])


def gap_min(root):
    pts = []
    for r in rows(root, "results/v7/analysis/gap_table_b4.csv"):
        o, t = r["seed points full_qc_logit original/retrained"].split(" / ")
        pts += [float(x) for x in re.findall(r"-?\d+\.\d+", o + " " + t)]
    assert len(pts) == 30
    return min(pts), None, None


def transfer_velocity(root):
    r = one(rows(root, "results/v11/analysis/t2_transfer.csv"), group="ours_v7_A_velocity")
    return float(r["auc"]), float(r["ci_lo"]), float(r["ci_hi"])


ROWS = [
    ("MWI, missing runs, low strength", effect("v7", "runs", "low", "SE(A_none)"), 3),
    ("MWI(mid) $-$ MWI(low), missing runs", effect("v7", "runs", "mid-low", "SE(mid) - SE(low), A_none"), 3),
    ("MWI, whole-joint absence", effect("v7", "whole", "mid", "SE(A_none)"), 3),
    ("Reference own-operator response, whole-joint absence", effect("v7", "whole", "mid", "SE(A_none)", "R_I"), 3),
    ("Interpolated control, whole-joint, standard minus control (first mask)", blind_whole, 3),
    ("Adversarial head, frozen frames, $\\Delta$MWI", adv("logit"), 3),
    ("\\quad same, raw AUROC", adv("raw"), 3),
    ("\\quad same, seeds and masks resampled (interval)", adv_crossed, 3),
    ("Whole-joint dropout $-$ none, arm confidence (v8 rule)", effect("v8", "armruns", "mid", "SE(A_dropout) - SE(A_none)"), 3),
    ("Coordinate dropout $-$ none, missing runs", effect("v7", "runs", "mid", "SE(B_coorddrop) - SE(A_none)"), 3),
    ("Real-split $\\Delta_{\\rm full\\to QC}$, smallest of 30 models (logit)", gap_min, 2),
    ("External AUROC, ours: velocity", transfer_velocity, 3),
]


def f(x, d, sign=True):
    s = f"{x:+.{d}f}" if sign else f"{x:.{d}f}"
    return s.replace("-", "$-$")


def cell(v, d, full, sign):
    p, lo, hi = v
    ci = f"[{f(lo, d, sign)}, {f(hi, d, sign)}]" if lo is not None else ""
    if p is None:
        return ci
    return f"{f(p, d, sign)} {ci}".strip() if full else f(p, d, sign)


bad = []
L = ["% generated by experiments/make_table_repair_compare.py from the historical results and the two"
     " release trees; do not edit",
     r"\begin{tabular}{p{0.38\linewidth}ccc}", r"\toprule",
     r"Quantity & Earlier & Rerun, original rule & Rerun, cleaned rule \\", r"\midrule"]
for name, get, d in ROWS:
    h, o, c = get(a.hist), get(a.orig), get(a.clean)
    sign = not name.startswith("External")
    if [round(x, 4) if x is not None else None for x in h] != [round(x, 4) if x is not None else None for x in o]:
        bad.append(f"original-rule rerun differs from historical: {name}: {h} vs {o}")
    if cell(h, d, True, sign) == cell(c, d, True, sign):
        bad.append(f"no change at printed precision: {name}")
    L.append(f"{name} & {cell(h, d, False, sign)} & {cell(o, d, False, sign)} & {cell(c, d, True, sign)} \\\\")
L += [r"\bottomrule", r"\end{tabular}"]
if bad:
    sys.exit("\n".join(bad))
open(a.out, "w").write("\n".join(L) + "\n")
print("wrote", a.out, len(ROWS), "rows")
