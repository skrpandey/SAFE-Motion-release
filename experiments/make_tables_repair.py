"""Supplement tables for the seed/mask variance of the v12 remedies and the full-to-QC gap,
from the repaired outputs. Writes paper/tables/{variance_v12,gap_b4}.tex.
Labels use MWI (archived field name SE)."""
import argparse, csv
ap = argparse.ArgumentParser()
ap.add_argument("--v12", default="results/v12/analysis/variance_v12.csv")
ap.add_argument("--gap", default="results/v7/analysis/gap_table_b4.csv")
ap.add_argument("--v7var", default="results/v7/analysis/variance_v7.csv")
a = ap.parse_args()
rows = [r for r in csv.DictReader(l for l in open(a.v12) if not l.startswith("#")) if not r["quantity"].startswith("R model")]
NAME = {"A_none": "no remedy", "C_groupdro": "Group DRO", "C_adversarial": "adversarial head", "C_augment": "operator augmentation"}
MECH = {"runs": "missing runs", "frozen": "frozen frames"}
import re as _re
m = lambda x: _re.sub(r"([+-]?\d+\.\d{4,})", lambda g: f"{float(g.group(1)):+.3f}" if g.group(1)[0] in "+-" else f"{float(g.group(1)):.3f}", x).replace("-", "$-$")   # three decimals
L = [r"\begin{tabular}{lllccccc}", r"\toprule",
     r"Mechanism & Cell & Quantity & Point & Conditional 95\% & Crossed-factor 95\% & Seed-combination range & Mask range \\", r"\midrule"]
# the crossed-factor interval of the no-remedy MWI comes from variance_v7.csv so it matches Table I;
# the remedy and Delta rows keep their own joint draws
V7 = {(r["proto"], r["mechanism"], r["strength"]): r for r in csv.DictReader(l for l in open(a.v7var) if not l.startswith("#"))}
PROTO = {"runs": "v7", "frozen": "v8"}
for r in rows:
    if r["cell"] == "A_none" and r["quantity"] == "SE":
        v = V7[(PROTO[r["mechanism"]], r["mechanism"], "mid")]
        assert abs(float(v["point"]) - float(r["point"])) < 5e-4, (v["point"], r["point"])
        r = dict(r, crossed_ci=v["crossed_ci"])
    q = "MWI" if r["quantity"] == "SE" else "$\\Delta$MWI"
    L.append(f"{MECH[r['mechanism']]} & {NAME[r['cell']]} & {q} & {m(f"{float(r['point']):+.3f}")} & {m(r['cond_ci'])} & {m(r['crossed_ci'])} & "
             f"{m(f'{float(r['seed_combo_min']):+.3f}')} to {m(f'{float(r['seed_combo_max']):+.3f}')} & {float(r['mask_range']):.3f} \\\\")
L += [r"\bottomrule", r"\end{tabular}", ""]
open("paper/tables/variance_v12.tex", "w").write("% generated by experiments/make_tables_repair.py; do not edit\n" + "\n".join(L))
g = list(csv.DictReader(l for l in open(a.gap) if not l.startswith("#")))
V = {"A_none": "none", "A_velocity": "velocity", "A_dropout": "whole-joint dropout", "A_both": "velocity + dropout", "B_coorddrop": "coordinate dropout"}
L = [r"\begin{tabular}{lccccc}", r"\toprule",
     r"Variant & $\Delta_{\rm full\to QC}$, original & retrained & retrained $-$ original & $\Delta_{\rm pass-fail}$ (raw), retrained $-$ original \\",
     r" & (logit) & (logit) & (logit) & \\", r"\midrule"]
for r in g:
    L.append(f"{V[r['variant']]} & {m(r['full_qc_logit original'])} & {m(r['full_qc_logit retrained'])} & {m(r['full_qc_logit retrained-original'])} & {m(r['pass_fail_raw retrained-original'])} \\\\")
L += [r"\bottomrule", r"\end{tabular}", ""]
open("paper/tables/gap_b4.tex", "w").write("% generated by experiments/make_tables_repair.py; do not edit\n" + "\n".join(L))
print("wrote variance_v12.tex, gap_b4.tex")
