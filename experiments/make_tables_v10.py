"""Paper tables for protocol v10 from results/v10/analysis.

Writes paper/tables/{blind_v10,real_ref_v10,masks_v10}.tex. Run after analyze_v10.py.
"""
import csv
import os

A = "results/v10/analysis"
OUT = "paper/tables"
MECH_NAME = {"runs": "missing runs", "whole": "whole-joint absence", "frozen": "frozen frames",
             "armruns": "arm confidence", "gapfill": "gap filling"}
CELL_NAME = {"A_none": "none", "A_velocity": "velocity", "A_dropout": "whole-joint dropout",
             "A_both": "velocity + dropout", "B_coorddrop": "coordinate dropout"}
HOST_NAME = {"mmasd_chest_squat": "MMASD", "utd_mhad_body_vs_arm": "UTD-MHAD"}
V7_SE = {"runs": 0.7562597909053703, "whole": 0.48282409036045476}   # effects.csv SE(A_none) mid, v7


def rows(name):
    with open(os.path.join(A, name)) as f:
        return list(csv.DictReader(f))


def num(x, d=3):
    return f"{float(x):+.{d}f}".replace("-", "$-$")


def ci(p, lo, hi, d=3):
    return f"{num(p, d)} [{num(lo, d)}, {num(hi, d)}]"


def write(name, lines):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w") as f:
        f.write("% generated by experiments/make_tables_v10.py from results/v10/analysis; do not edit\n")
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.join(OUT, name))


def blind():
    import json
    c = json.load(open(os.path.join(A, "criteria.json")))["A1_cue_attributable"]
    header = r"Mechanism & SE, standard cell (v7) & SE, interpolated control & Control-to-standard ratio & Rule A1 \\"
    if not c:
        # the committed criteria.json has an empty A1 block (partial rerun of analyze_v10):
        # keep the numbers of the existing table and only update its header
        path = os.path.join(OUT, "blind_v10.tex")
        old = open(path).read().splitlines()
        k = next(i for i, l in enumerate(old) if l.startswith("Mechanism &"))
        old[k] = header
        open(path, "w").write("\n".join(old) + "\n")
        print("relabelled", path, "(A1 block empty; numbers kept)")
        return
    lines = [r"\begin{tabular}{lcccc}", r"\toprule", header, r"\midrule"]
    for mech in ("runs", "whole"):
        e = c[mech]
        lines.append(f"{MECH_NAME[mech]} & {num(e['SE_none'])} & {ci(*e['SE_blind'])} & "
                     f"{ci(*e['share'], d=2)} & {'pass' if e['pass'] else 'fail'} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("blind_v10.tex", lines)


def real_ref():
    import json
    c = json.load(open(os.path.join(A, "criteria.json")))["B_real_world_I"]
    ops = ["runs", "whole", "frozen", "armruns", "gapfill"]
    lines = [r"\begin{tabular}{l" + "c" * len(ops) + "}", r"\toprule",
             r"Model & " + " & ".join(MECH_NAME[o] for o in ops) + r" \\", r"\midrule"]
    for cell in ("A_none", "A_velocity", "A_dropout", "A_both", "B_coorddrop"):
        cells = []
        for o in ops:
            v = c[cell][o]
            d = ci(*v["diff"], d=2)
            if v["excludes_zero"]:
                d = r"\textbf{" + d + "}"
            cells.append(f"{num(v['R_v7'], 2)} / {num(v['R_ref'], 2)} / {d}")
        lines.append(f"{CELL_NAME[cell]} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("real_ref_v10.tex", lines)


def masks():
    lines = [r"\begin{tabular}{llcccc}", r"\toprule",
             r"Host & Mechanism & SE, v9 (one mask) & SE, mean of 10 masks & Between-mask SD & Range \\", r"\midrule"]
    v9 = {(x["host"], x["mechanism"], x["strength"]): x["point"] for x in csv.DictReader(open("results/v9/analysis/effects.csv"))
          if x["contrast"] == "SE(A_none)"}   # single source for the v9 one-mask value
    for r in rows("masks.csv"):
        r = dict(r, SE_v9_mask2000=v9.get((r["host"], r["mechanism"], r["strength"]), r["SE_v9_mask2000"]))
        mech = MECH_NAME[r["mechanism"]] + (" (low)" if r["strength"] == "low" else "")
        lines.append(f"{HOST_NAME[r['host']]} & {mech} & {num(r['SE_v9_mask2000'])} & "
                     f"{ci(r['SE_mean'], r['ci_lo'], r['ci_hi'])} & {float(r['SE_between_mask_sd']):.3f} & "
                     f"{num(r['SE_min'], 2)} to {num(r['SE_max'], 2)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("masks_v10.tex", lines)


if __name__ == "__main__":
    blind()
    real_ref()
    masks()
