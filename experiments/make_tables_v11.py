"""Paper tables for protocol v11, generated from results/v11/analysis (no hand-typed numbers).

Writes paper/tables/v11_*.tex (quality, transfer, contrasts, controls, ceiling, operators,
calibration, position, head refit, and short/supplement variants). Run after analyze_v11.py.
"""
import csv
import os

A = "results/v11/analysis"
OUT = "paper/tables"
GROUP_NAME = {"v1": "SAFE-SMM v1", "v2_family": "SAFE-SMM v2 (3 seeds)", "v3": "SAFE-SMM v3",
              "v3_noconf_family": "v3, no confidence (3)", "base_no_remedies": "base, no remedies",
              "abl_velocity": "velocity only", "abl_dropout": "dropout only",
              "abl_velocity_v3norm": "velocity only, v3 norm.", "abl_dropout_v3norm": "dropout only, v3 norm.",
              "permuted_v1": "permuted control v1", "permuted_v2": "permuted control v2",
              "stgcn_base": "ST-GCN base", "stgcn_remedies": "ST-GCN remedies",
              "agcn_base": "AGCN base", "agcn_remedies": "AGCN remedies"}
CELL = {"A_none": "none", "A_velocity": "velocity", "A_dropout": "whole-joint dropout",
        "A_both": "velocity + dropout", "B_coorddrop": "coordinate dropout"}
MECH = {"runs": "missing runs", "whole": "whole-joint absence", "frozen": "frozen frames",
        "armruns": "arm confidence", "gapfill": "gap filling"}


def gname(g):
    if g in GROUP_NAME:
        return GROUP_NAME[g]
    for pre, lab in (("ours_v7_", "ours: "), ("ours_v10_", "ours, real-data World I: ")):
        if g.startswith(pre):
            return lab + CELL.get(g[len(pre):], g[len(pre):])
    return g.replace("_", " ")


def rows(name):
    p = os.path.join(A, name)
    if not os.path.exists(p) or os.path.getsize(p) == 0:
        return []
    with open(p) as f:
        return list(csv.DictReader(f))


def f(x, d=3, sign=False):
    if x in ("", None):
        return ""
    v = float(x)
    if v != v:
        return "n/a"
    s = f"{v:+.{d}f}" if sign else f"{v:.{d}f}"
    return s.replace("-", "$-$")


def ci(p, lo, hi, d=3, sign=False):
    return f"{f(p, d, sign)} [{f(lo, d, sign)}, {f(hi, d, sign)}]"


def write(name, lines):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w") as fh:
        fh.write("% generated by experiments/make_tables_v11.py from results/v11/analysis; do not edit\n")
        fh.write("\n".join(lines) + "\n")
    print("wrote", os.path.join(OUT, name))


def quality():
    r = rows("t1_quality.csv")
    m = rows("t4_quality.csv")
    lines = [r"\begin{tabular}{llccc}", r"\toprule",
             r"Extractor & Quality-only classifier & AUC [95\% CI] & Null 95th pct. & Permutation $p$ \\", r"\midrule"]
    for x in r:
        lines.append(f"RTMPose & {x['classifier'].replace('_', ' ')} & {ci(x['auc'], x['ci_lo'], x['ci_hi'])} & "
                     f"{f(x['null_p95'])} & {f(x['perm_p'])} \\\\")
    for x in sorted(m, key=lambda x: not x["classifier"].startswith("asdpose")):
        if x["classifier"].startswith("within_set") or x["classifier"] == "asdpose_fit_lr":
            lines.append(f"MediaPipe & {x['classifier'].replace('_', ' ')} & {ci(x['auc'], x['ci_lo'], x['ci_hi'])} & "
                         f"{f(x['null_p95'])} & {f(x['perm_p'])} \\\\")
    lines += [r"\midrule", r"ASDPose, standard split (reference) & logistic regression & 0.714 & & \\",
              r"\bottomrule", r"\end{tabular}"]
    write("v11_quality.tex", lines)


def transfer():
    r = rows("t2_transfer.csv")
    cats = [k[4:] for k in r[0] if k.startswith("auc_") and not k.endswith(("_lo", "_hi"))] if r else []
    lines = [r"\begin{tabular}{lcc" + "c" * len(cats) + "cc}", r"\toprule",
             r"Model & ASDPose AUC & External AUC [95\% CI] & " + " & ".join(c.replace("_", " ") for c in cats)
             + r" & Firing at 0.85 & False alarms at 0.85 \\", r"\midrule"]
    order = sorted(r, key=lambda x: (not x["group"].startswith("ours_v7"), not x["group"].startswith("ours_v10"), x["group"]))
    for x in order:
        cells = [f(x[f"auc_{c}"], 2) for c in cats]
        lines.append(f"{gname(x['group'])} & {f(x['asdpose_auc'])} & {ci(x['auc'], x['ci_lo'], x['ci_hi'])} & "
                     + " & ".join(cells) + f" & {f(x['firing_085'], 2)} & {f(x['false_alarm_085'], 2)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("v11_transfer.tex", lines)


def contrasts():
    r = [x for x in rows("t2_contrasts.csv") if x["scale"] == "raw AUC"]
    lines = [r"\begin{tabular}{lc}", r"\toprule", r"Contrast (external AUC) & Difference [95\% CI] \\", r"\midrule"]
    for x in r:
        lines.append(f"{x['contrast'].replace('_', ' ')} & {ci(x['point'], x['ci_lo'], x['ci_hi'], sign=True)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("v11_contrasts.tex", lines)


def confidence_and_estimator():
    t3 = {x["group"]: x for x in rows("t3_confidence.csv")}
    t4 = {x["group"]: x for x in rows("t4_estimator.csv")}
    t6 = {x["group"]: x for x in rows("t6_dfr.csv")}
    lines = [r"\begin{tabular}{lcccc}", r"\toprule",
             r"Model & External AUC & Confidence zeroed, $\Delta$ & MediaPipe input, $\Delta$ & Last layer refit (DFR), $\Delta$ \\", r"\midrule"]
    for g in sorted(set(t3) | set(t4) | set(t6), key=lambda x: (not x.startswith("ours_v7"), not x.startswith("ours_v10"), x)):
        base = t3.get(g) or t4.get(g) or t6.get(g)
        auc = base.get("auc_rtmpose") or base.get("auc_full") or ""
        if not auc and g in t3:
            auc = f"{float(t3[g]['auc_conf0']) - float(t3[g]['point']):.4f}"
        c3 = ci(t3[g]["point"], t3[g]["ci_lo"], t3[g]["ci_hi"], sign=True) if g in t3 else ""
        c4 = ci(t4[g]["point"], t4[g]["ci_lo"], t4[g]["ci_hi"], sign=True) if g in t4 else ""
        c6 = ci(t6[g]["point"], t6[g]["ci_lo"], t6[g]["ci_hi"], sign=True) if g in t6 else ""
        lines.append(f"{gname(g)} & {f(auc)} & {c3} & {c4} & {c6} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("v11_controls.tex", lines)
    c = rows("t6_ceiling.csv")
    lines = [r"\begin{tabular}{lcc}", r"\toprule", r"Architecture trained within the set & Out-of-fold AUC [95\% CI] & Per seed \\", r"\midrule"]
    for x in c:
        lines.append(f"{x['arch']} & {ci(x['oof_auc'], x['ci_lo'], x['ci_hi'])} & {x['per_seed']} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("v11_ceiling.tex", lines)


def operators():
    r = [x for x in rows("t5_operators.csv") if x["mask_seed"] == "2000"]
    mechs = ["runs", "whole", "frozen", "armruns", "gapfill"]
    lines = [r"\begin{tabular}{l" + "c" * len(mechs) + "}", r"\toprule",
             r"Model & " + " & ".join(MECH[m] for m in mechs) + r" \\", r"\midrule"]
    for cell in ("A_none", "A_velocity", "A_dropout", "A_both", "B_coorddrop"):
        cells = []
        for m in mechs:
            x = next((z for z in r if z["cell"] == cell and z["mechanism"] == m), None)
            if x is None:
                cells.append("")
                continue
            d = ci(x["diff_point"], x["diff_lo"], x["diff_hi"], 2, sign=True) if x.get("diff_point") else ""
            if x.get("diff_excludes_zero") == "True":
                d = r"\textbf{" + d + "}"
            cells.append(f"{f(x['point'], 2, True)} / {f(x.get('R_ref', ''), 2, True)} / {d}")
        lines.append(f"{CELL[cell]} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write("v11_operators.tex", lines)


