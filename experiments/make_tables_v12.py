"""Paper table for protocol v12 (cue-targeted remedies), generated from results/v12/analysis.

Writes paper/tables/remedies_v12.tex (no hand-typed numbers). Run after analyze_v12.py.
    python experiments/make_tables_v12.py [--analysis results/v12/analysis] [--out paper/tables/remedies_v12.tex]
"""
import argparse
import csv
import json
import os

NAMES = {"C_groupdro": "Group DRO", "C_adversarial": "adversarial head", "C_augment": "operator augmentation"}
MECH = {"runs": "missing runs", "frozen": "frozen frames"}


def tex(s):
    return s.replace("-", "$-$") if s else ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--analysis", default="results/v12/analysis")
    ap.add_argument("--out", default="paper/tables/remedies_v12.tex")
    args = ap.parse_args()
    rows = list(csv.DictReader(open(f"{args.analysis}/effects.csv")))
    crit = json.load(open(f"{args.analysis}/criteria.json"))
    lines = [r"\begin{tabular}{llccccc}", r"\toprule",
             r"Mechanism & Method & SE & Change in SE (logit) & Change in SE (raw AUC) & "
             r"Clean AUC change, World I & Lowers SE \\", r"\midrule"]
    for mech in ("runs", "frozen"):
        base = [r for r in rows if r["mechanism"] == mech and r["contrast"] == "SE(A_none)"]
        if not base:
            continue
        lines.append(f"{MECH[mech]} & none & {tex(base[0]['logit'])} & & & & \\\\")
        for cell, name in NAMES.items():
            se = [r for r in rows if r["mechanism"] == mech and r["contrast"] == f"SE({cell})"]
            d = [r for r in rows if r["mechanism"] == mech and r["contrast"] == f"SE({cell}) - SE(A_none)"]
            if not se or not d:
                continue
            c = crit["P12_2"].get(f"{cell}|{mech}|I", {}).get("clean_auc_change")
            cs = f"{c[0]:+.3f} [{c[1]:+.3f}, {c[2]:+.3f}]" if c else ""
            ok = "yes" if crit["P12_1"].get(f"{cell}|{mech}", {}).get("pass") else "no"
            lines.append(f" & {name} & {tex(se[0]['logit'])} & {tex(d[0]['logit'])} & {tex(d[0]['raw'])} & "
                         f"{tex(cs)} & {ok} \\\\")
        lines.append(r"\addlinespace")
    lines[-1:] = [r"\bottomrule", r"\end{tabular}"]
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w") as f:
        f.write("% generated by experiments/make_tables_v12.py from results/v12/analysis; do not edit\n")
        f.write("\n".join(lines) + "\n")
    print("wrote", args.out)


if __name__ == "__main__":
    main()
