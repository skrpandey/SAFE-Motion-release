"""Full remedy table for protocol v12: world-by-policy AUROCs, both responses, the interaction
and clean AUROC per world, method and mechanism.

Superseded: main() exits at once. It took the logit of the seed-mean AUROC; the table is now
written by experiments/make_tables_v6.py (logit per seed and mask, then the mean).
"""
import csv
import glob
import os

import numpy as np
from sklearn.metrics import roc_auc_score

MASKS = (2000, 3000, 4000)
NAME = {"A_none": "none", "C_groupdro": "Group DRO", "C_adversarial": "adversarial head",
        "C_augment": "operator augmentation"}
MECH = {"runs": "missing runs", "frozen": "frozen frames"}


def files(mech, world, cell):
    if cell == "A_none":
        pat = f"results/v7/scores/{'v7' if mech == 'runs' else 'v8'}_{world}_w0_{mech}_mid_A_none_s*.csv"
    else:
        pat = f"results/v12/scores/v12_{world}_w0_{mech}_mid_{cell}_s*.csv"
    out = sorted(glob.glob(pat))
    assert len(out) == 3, (pat, out)
    return out


def aucs(path, mech):
    rows = list(csv.DictReader(open(path)))
    y = np.array([int(r["label"]) for r in rows])
    col = lambda c: np.array([float(r[c]) for r in rows])
    res = {"clean": roc_auc_score(y, col("clean"))}
    for pol in ("S", "I"):
        res[pol] = np.mean([roc_auc_score(y, col(f"{mech}_{pol}_mid_m{m}")) for m in MASKS])
    return res


def logit(a):
    a = min(max(a, 1e-6), 1 - 1e-6)
    return np.log(a / (1 - a))


def main():
    raise SystemExit("superseded: run experiments/make_tables_v6.py (draft v6)")
    lines = [r"\begin{tabular}{llccccccccc}", r"\toprule",
             r"Mechanism & Method & $m(S,S)$ & $m(S,I)$ & $m(I,S)$ & $m(I,I)$ & $R(f_S)$ & $R(f_I)$ & SE (logit) & SE (raw) & clean S / I \\",
             r"\midrule"]
    for mech in ("runs", "frozen"):
        first = True
        for cell in ("A_none", "C_groupdro", "C_adversarial", "C_augment"):
            per = {}
            for w in ("S", "I"):
                a = [aucs(p, mech) for p in files(mech, w, cell)]
                per[w] = {k: float(np.mean([x[k] for x in a])) for k in ("clean", "S", "I")}
            mSS, mSI, mIS, mII = (logit(per["S"]["S"]), logit(per["S"]["I"]),
                                  logit(per["I"]["S"]), logit(per["I"]["I"]))
            rs, ri = mSS - mSI, mIS - mII
            raw = (per["S"]["S"] - per["S"]["I"]) - (per["I"]["S"] - per["I"]["I"])
            lab = MECH[mech] if first else ""
            first = False
            lines.append(f"{lab} & {NAME[cell]} & {per['S']['S']:.3f} & {per['S']['I']:.3f} & {per['I']['S']:.3f} & "
                         f"{per['I']['I']:.3f} & {rs:+.3f} & {ri:+.3f} & {rs - ri:+.3f} & {raw:+.3f} & "
                         f"{per['S']['clean']:.3f} / {per['I']['clean']:.3f} \\\\".replace("-", "$-$"))
        lines.append(r"\addlinespace")
    lines[-1:] = [r"\bottomrule", r"\end{tabular}"]
    os.makedirs("paper/tables", exist_ok=True)
    with open("paper/tables/remedies_v12_full.tex", "w") as f:
        f.write("% generated by experiments/make_tables_v12_full.py from results/v7, v8 and v12 scores; do not edit\n")
        f.write("\n".join(lines) + "\n")
    print("wrote paper/tables/remedies_v12_full.tex")


if __name__ == "__main__":
    main()
