"""Paper table for protocol v13 (arm-confidence cells under the coordinate-invariant rule),
generated from results/v13/analysis (no hand-typed numbers). Run after analyze_v13.py.
    python experiments/make_tables_v13.py [--analysis results/v13/analysis] [--out paper/tables/armconf_v13.tex]
"""
import argparse
import csv
import json
import os


def tex(s):
    return s.replace("-", "$-$") if s else ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--analysis", default="results/v13/analysis")
    ap.add_argument("--out", default="paper/tables/armconf_v13.tex")
    args = ap.parse_args()
    rows = list(csv.DictReader(open(f"{args.analysis}/effects.csv")))
    crit = json.load(open(f"{args.analysis}/criteria.json"))
    g = crit.get("V13_1_invariance", {})
    names = {"v8": "confidence $>$ 0 (protocols v7, v8)", "v13": "nonzero coordinates (protocol v13)"}
    lines = [r"\begin{tabular}{lcccccc}", r"\toprule",
             r"Valid-joint rule & $R(f_S)$ & $R(f_I)$ & SE (logit) & SE (raw AUROC) & Seed SD & Mask range \\",
             r"\midrule"]
    for key, name in names.items():
        r = [x for x in rows if x["proto"] == key and x["contrast"].startswith("SE(A_none)")]
        if not r:
            continue
        r = r[0]
        lines.append(f"{name} & {tex(r['R_S'])} & {tex(r['R_I'])} & {tex(r['logit'])} & {tex(r['raw'])} & "
                     f"{r['sd_seeds']} & {r['mask_range']} \\\\")
    d = [x for x in rows if x["proto"] == "v13 - v8" and x["contrast"].startswith("SE(v13)")]
    if d:
        lines.append(r"\midrule")
        lines.append(f"difference, v13 minus v8 & & & {tex(d[0]['logit'])} & {tex(d[0]['raw'])} & & \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w") as f:
        f.write("% generated by experiments/make_tables_v13.py from results/v13/analysis; do not edit\n")
        f.write(f"% V13_1 invariance gate: {'PASS' if g.get('pass') else 'FAIL'} "
                f"(max abs x,y difference {g.get('max_abs_diff_xy')}, {g.get('n_segments')} segments)\n")
        f.write("\n".join(lines) + "\n")
    print("wrote", args.out)


if __name__ == "__main__":
    main()
