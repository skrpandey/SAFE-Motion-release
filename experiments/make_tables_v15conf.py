"""Paper table for protocol v15conf (Group DRO under confidence-only planting with the
coordinate-invariant rule). Run after analyze_v15conf.py.
    python experiments/make_tables_v15conf.py [--analysis results/v15conf/clean/analysis]
        [--out paper/tables/remedies_confonly_v15.tex]
"""
import argparse
import re
import csv
import json
import os

NAMES = {"A_none": "no remedy", "C_groupdro": "Group DRO"}


def tex(s):
    """Round numbers to at most three decimals and typeset minus signs."""
    if not s:
        return ""
    s = re.sub(r"([+-]?\d+\.\d{4,})", lambda m: f"{float(m.group(1)):+.3f}" if m.group(1)[0] in "+-" else f"{float(m.group(1)):.3f}", s)
    return s.replace("-", "$-$")


def pt(s):
    """Point estimate only, rounded (not truncated) to three decimals; the interval is in the
    analysis CSV. (Until 2026-11-11 the string was cut after six characters, which printed
    +0.6056 as +0.605 and +0.0555 as +0.055; Tables S2 and S4 round the same values to +0.606
    and +0.056.)"""
    return tex(f"{float(s.split(' [')[0]):+.4f}") if s else ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--analysis", default="results/v15conf/clean/analysis")
    ap.add_argument("--out", default="paper/tables/remedies_confonly_v15.tex")
    args = ap.parse_args()
    rows = list(csv.DictReader(open(f"{args.analysis}/effects.csv")))
    crit = json.load(open(f"{args.analysis}/criteria.json"))
    by = {r["contrast"]: r for r in rows}
    lines = [r"\begin{tabular}{lcccc}", r"\toprule",
             r"Quantity & $R(f_S)$ & $R(f_I)$ & Logit & Raw AUROC \\", r"\midrule"]
    for cell in ("A_none", "C_groupdro"):
        r = by[f"MWI({cell})"]
        lines.append(f"MWI, {NAMES[cell]} & {pt(r['R_S'])} & {pt(r['R_I'])} & {tex(r['logit'])} & {tex(r['raw'])} \\\\")
    d = by["MWI(C_groupdro) - MWI(A_none)"]
    lines += [r"\midrule",
              f"Change in MWI, Group DRO minus no remedy & & & {tex(d['logit'])} & {tex(d['raw'])} \\\\",
              f"\\quad inversion $p$ & & & {d['p_inv']} & {d['raw_p_inv']} \\\\"]
    s_l = by.get("MWI(C_groupdro) - MWI(A_none), seeds and masks resampled (logit)", {}).get("logit", "")
    s_r = by.get("MWI(C_groupdro) - MWI(A_none), seeds and masks resampled (raw)", {}).get("raw", "")
    lines.append(f"\\quad seeds and masks resampled & & & {tex(s_l)} & {tex(s_r)} \\\\")
    for w in ("S", "I"):
        c = by.get(f"clean AUROC(C_groupdro) - clean AUROC(A_none), World {w}")
        if c:
            lines.append(f"Clean AUROC change, World {w} & & & & {tex(c['raw'])} \\\\")
    v13 = by.get("MWI(A_none, v13 cleaned)")
    dd = by.get("MWI(A_none, v15conf) - MWI(A_none, v13 cleaned) [descriptive]")
    if v13 and dd:
        lines += [r"\midrule",
                  f"MWI, no remedy, original recipe & {pt(v13['R_S'])} & {pt(v13['R_I'])} & "
                  f"{tex(v13['logit'])} & {tex(v13['raw'])} \\\\",
                  f"\\quad difference, corrected minus original recipe (descriptive) & & & {tex(dd['logit'])} & {tex(dd['raw'])} \\\\"]
    lines += [r"\bottomrule", r"\end{tabular}"]
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w") as f:
        f.write(f"% generated by experiments/make_tables_v15conf.py from {args.analysis}; do not edit\n")
        f.write(f"% P15_1 lowers MWI on both scales: {'YES' if crit['P15_1']['pass'] else 'NO'}; "
                f"rows {crit['n_rows']}, clusters {crit['n_clusters']}, resamples {crit['n_boot']}\n")
        f.write("\n".join(lines) + "\n")
    print("wrote", args.out)


if __name__ == "__main__":
    main()
