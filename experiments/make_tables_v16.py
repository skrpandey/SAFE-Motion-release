"""Supplement tables of protocol v16 from results/v16/analysis/{effects.csv, criteria.json, conf_reliance.csv}.

paper/tables/v16_cells.tex: per cell, MWI (logit, raw), the seed-and-mask sensitivity interval, R(f_I), clean
AUROC S - I, and confidence-permutation reliance (World S minus World I) on clean and on planted policy S input.
paper/tables/v16_contrasts.tex: Group DRO with observed groups against no remedy and against severity groups,
its clean-AUROC change, and ST-GCN against CompactCTRGCN.
    python experiments/make_tables_v16.py
"""
import csv
import json
import re

A = "results/v16/analysis"
NUM = re.compile(r"[+-]?\d+\.\d+")


def rows(path):
    return list(csv.DictReader(l for l in open(path) if not l.startswith("#")))


def r3(s):
    """Round every number in s once to three decimals; refuse values on a rounding boundary."""
    def one(m):
        t = m.group()
        assert not re.search(r"\.\d{3}50*$", t.lstrip("+-")), f"value on a rounding boundary: {t}"
        return f"{float(t):+.3f}"
    return NUM.sub(one, s).replace("-", "$-$")


def main():
    eff = {r["quantity"]: r for r in rows(f"{A}/effects.csv")}
    import os
    # the permutation-reliance scores exist for the cleaned selection only; the orig tree prints a dash
    rel = {r["group"]: r for r in rows(f"{A}/conf_reliance.csv")} if os.path.exists(f"{A}/conf_reliance.csv") else {}
    dash = {"clean_S_minus_I": "--", "policyS_S_minus_I": "--"}
    crit = json.load(open(f"{A}/criteria.json"))
    cells = (("ST-GCN, no remedy", "A", "3", "ST-GCN, no remedy"),
             ("CompactCTRGCN, no remedy, seeds 0--2 (v15conf)", "base3", "3", "CompactCTRGCN, no remedy, seeds 0-2"),
             ("CompactCTRGCN, no remedy", "base9", "9", "CompactCTRGCN, no remedy, nine seeds"),
             ("CompactCTRGCN, Group DRO, observed groups", "C", "3", "CompactCTRGCN, Group DRO with observed groups"))
    L = [r"\begin{tabular}{lcccccccc}", r"\toprule",
         r" & & \multicolumn{2}{c}{MWI} & Seeds, masks & & Clean AUROC & \multicolumn{2}{c}{Permutation, $f_S - f_I$} \\",
         r"\cmidrule(lr){3-4}\cmidrule(lr){8-9}",
         r"Cell & Seeds & logit & raw & resampled & $R(f_I)$ & $S - I$ & clean input & policy S input \\", r"\midrule"]
    for label, key, n, rkey in cells:
        e = eff[f"MWI ({key})"]
        sens = NUM.findall(eff[f"MWI ({key}), seeds and masks resampled (logit)"]["logit"])
        L.append(f"{label} & {n} & {r3(e['logit'])} & {r3(e['raw'])} & {r3(f'[{sens[1]}, {sens[2]}]')} & "
                 f"{r3(e['R_I'])} & {r3(e['clean_S_minus_I'])} & {r3(rel.get(rkey, dash)['clean_S_minus_I'])} & "
                 f"{r3(rel.get(rkey, dash)['policyS_S_minus_I'])} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    with open("paper/tables/v16_cells.tex", "w") as f:
        f.write("% generated by experiments/make_tables_v16.py from results/v16/analysis; do not edit\n" + "\n".join(L) + "\n")
    w = crit["P16_B1_precision"]["welch_t"]
    c = crit["P16_C1_reduction"]
    K = [r"\begin{tabular}{lcc}", r"\toprule", r"Contrast & logit & raw AUROC \\", r"\midrule",
         f"Group DRO, observed groups, minus no remedy (seeds 0--2) & {r3(eff['MWI(C_groupdro_obs) - MWI(A_none, v15conf seeds 0-2)']['logit'])} & "
         f"{r3(eff['MWI(C_groupdro_obs) - MWI(A_none, v15conf seeds 0-2)']['raw'])} \\\\",
         f"\\quad seeds and masks resampled & "
         f"{r3(eff['MWI(C_groupdro_obs) - MWI(A_none, v15conf seeds 0-2), seeds and masks resampled (logit)']['logit'])} & "
         f"{r3(eff['MWI(C_groupdro_obs) - MWI(A_none, v15conf seeds 0-2), seeds and masks resampled (raw)']['raw'])} \\\\",
         f"\\quad against no remedy with nine seeds & {r3(eff['MWI(C_groupdro_obs) - MWI(A_none, nine seeds) [sensitivity]']['logit'])} & "
         f"{r3(eff['MWI(C_groupdro_obs) - MWI(A_none, nine seeds) [sensitivity]']['raw'])} \\\\",
         f"\\quad seeds and masks resampled & "
         f"{r3(eff['MWI(C_groupdro_obs) - MWI(A_none, nine seeds), seeds and masks resampled (logit)']['logit'])} & "
         f"{r3(eff['MWI(C_groupdro_obs) - MWI(A_none, nine seeds), seeds and masks resampled (raw)']['raw'])} \\\\",
         f"\\quad against Group DRO with severity groups (descriptive) & "
         f"{r3(eff['MWI(C_groupdro_obs) - MWI(C_groupdro, v15conf, severity groups) [descriptive]']['logit'])} & "
         f"{r3(eff['MWI(C_groupdro_obs) - MWI(C_groupdro, v15conf, severity groups) [descriptive]']['raw'])} \\\\",
         f"\\quad clean AUROC change, World S & & {r3(eff['clean AUROC(C_groupdro_obs) - clean AUROC(A_none), World S']['raw'])} \\\\",
         f"\\quad clean AUROC change, World I & & {r3(eff['clean AUROC(C_groupdro_obs) - clean AUROC(A_none), World I']['raw'])} \\\\",
         r"\midrule",
         f"MWI, ST-GCN minus CompactCTRGCN (seeds 0--2; descriptive) & "
         f"{r3(eff['MWI(ST-GCN) - MWI(CompactCTRGCN, v15conf seeds 0-2) [descriptive]']['logit'])} & "
         f"{r3(eff['MWI(ST-GCN) - MWI(CompactCTRGCN, v15conf seeds 0-2) [descriptive]']['raw'])} \\\\",
         f"MWI, CompactCTRGCN no remedy, nine seeds: seed-level $t$ interval & {r3(f'{w[0]:+.5f} [{w[1]:+.5f}, {w[2]:+.5f}]')} & \\\\",
         r"\bottomrule", r"\end{tabular}"]
    with open("paper/tables/v16_contrasts.tex", "w") as f:
        f.write("% generated by experiments/make_tables_v16.py from results/v16/analysis; do not edit\n" + "\n".join(K) + "\n")
    confonly_main(eff)
    print("wrote paper/tables/v16_cells.tex, v16_contrasts.tex and confonly_main.tex; group agreement",
          {k[-25:]: round(v, 3) for k, v in c["group_agreement"].items()})


def confonly_main(eff):
    """Main-text table of the confidence-only no-remedy estimates: the historical-recipe three-seed
    cell (protocol v13, from results/v13/analysis/cells_v6.csv as Table I prints it), the
    corrected-recipe three-seed cell (v15conf), the nine-seed cell and ST-GCN (v16)."""
    v13 = [r for r in csv.DictReader(open("results/v13/analysis/cells_v6.csv"))
           if r["proto"] == "v13" and r["mechanism"] == "armruns" and r["strength"] == "mid"]
    assert len(v13) == 1, v13
    v = {k: float(x) for k, x in v13[0].items() if k not in ("proto", "mechanism", "strength")}
    sens13 = sensitivity_v13()
    fmt = lambda k: r3(f"{v[k]:+.5f} [{v[k + '_lo']:+.5f}, {v[k + '_hi']:+.5f}]")
    L = [r"\begin{tabular}{llccccc}", r"\toprule",
         r" & & & \multicolumn{2}{c}{MWI} & Seeds, masks & Clean AUROC \\", r"\cmidrule(lr){4-5}",
         r"Network & Loader recipe & Seeds & logit & raw & resampled & $S - I$ \\", r"\midrule",
         f"CompactCTRGCN & historical & 3 & {fmt('SE')} & {fmt('SEraw')} & {sens13} & {fmt('cleanSI')} \\\\"]
    for label, key, n in (("CompactCTRGCN & corrected", "base3", "3"), ("CompactCTRGCN & corrected", "base9", "9"),
                          ("ST-GCN & corrected", "A", "3")):
        e = eff[f"MWI ({key})"]
        sens = NUM.findall(eff[f"MWI ({key}), seeds and masks resampled (logit)"]["logit"])
        L.append(f"{label} & {n} & {r3(e['logit'])} & {r3(e['raw'])} & {r3(f'[{sens[1]}, {sens[2]}]')} & "
                 f"{r3(e['clean_S_minus_I'])} \\\\")
    # protocol v17 (regenerated training assignments), appended when its analysis exists
    import os
    v17 = "results/v17/analysis"
    if os.path.exists(f"{v17}/effects.csv"):
        e17 = {r["quantity"]: r for r in rows(f"{v17}/effects.csv")}
        c17 = json.load(open(f"{v17}/criteria.json"))
        L.append(r"\midrule")
        for ws in (1, 2, 3):
            e = e17[f"MWI (w{ws})"]
            sens = NUM.findall(e17[f"MWI (w{ws}), seeds and masks resampled (logit)"]["logit"])
            L.append(f"CompactCTRGCN & corrected, assignment {ws} & 3 & {r3(e['logit'])} & {r3(e['raw'])} & "
                     f"{r3(f'[{sens[1]}, {sens[2]}]')} & {r3(e['clean_S_minus_I'])} \\\\")
        sp = c17["D17_2_assignment_spread"]["spread"]
        lg, rw = sp["world seeds 1-3 (logit)"], sp["world seeds 1-3 (raw)"]
        L.append(f"\\quad mean (SD) over assignments 1--3 & & 3 $\\times$ 3 & {lg['mean']:+.3f} ({lg['sd']:.3f}) & "
                 f"{rw['mean']:+.3f} ({rw['sd']:.3f}) & & \\\\".replace("-", "$-$").replace("$-$$-$", "--"))
    L += [r"\bottomrule", r"\end{tabular}"]
    with open("paper/tables/confonly_main.tex", "w") as f:
        f.write("% generated by experiments/make_tables_v16.py from results/v16/analysis, results/v13/analysis/cells_v6.csv "
                "and, when present, results/v17/analysis; do not edit\n" + "\n".join(L) + "\n")


def sensitivity_v13():
    """The seed-and-mask sensitivity interval of the v13 arm-confidence cell as Table I prints it
    (paper/tables/planted_v6.tex, column 5 of the arm-confidence row; its source is
    results/v13/analysis/variance or procedure_checks, which make_tables_v6.py reads)."""
    for line in open("paper/tables/planted_v6.tex"):
        if line.startswith("arm confidence"):
            return line.split("&")[4].strip()
    raise SystemExit("arm-confidence row not found in paper/tables/planted_v6.tex")


if __name__ == "__main__":
    main()
