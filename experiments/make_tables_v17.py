"""Supplement tables of protocol v17 from results/v17/analysis/{effects.csv, criteria.json,
assignment_severities.csv}.

paper/tables/v17_assignments.tex: per training assignment (world seed 0 = v15conf, 1-3 = v17),
World I clean AUROC (gate), MWI (logit, raw), the seed-and-mask sensitivity interval, R(f_I) and
clean AUROC S - I; then the mean (SD) across world seeds 1-3 and the pooled nine-fit estimate.
paper/tables/v17_assignment_severities.tex: realized severities and planted cue strength per
assignment and world (experiments/assignment_severities_v17.py).
    python experiments/make_tables_v17.py
"""
import csv
import json
import re

A = "results/v17/analysis"
NUM = re.compile(r"[+-]?\d+\.\d+")


def rows(path):
    return list(csv.DictReader(l for l in open(path) if not l.startswith("#")))


def r3(s):
    """Round every number in s once to three decimals; refuse values on a rounding boundary."""
    def one(m):
        t = m.group()
        assert not re.search(r"\.\d{3}50*$", t.lstrip("+-")), f"value on a rounding boundary: {t}"
        return f"{float(t):+.3f}"
    return NUM.sub(one, s).replace("-", "$-$")


def _v16_sens_w0():
    """Seed-and-mask interval of the corrected three-seed no-remedy cell (world seed 0) as the v16 analysis
    reports it (main Table 2, Table S18); the v17 analysis draws its own resamples and differs in the third
    decimal, so the table prints the v16 value and the caption says so."""
    import os
    p = "results/v16/analysis/effects.csv"
    if not os.path.exists(p):
        return None
    e = {r["quantity"]: r for r in rows(p)}
    q = "MWI (base3), seeds and masks resampled (logit)"
    return NUM.findall(e[q]["logit"]) if q in e else None


V16_SENS_W0 = None


def assignments():
    global V16_SENS_W0
    V16_SENS_W0 = _v16_sens_w0()
    eff = {r["quantity"]: r for r in rows(f"{A}/effects.csv")}
    crit = json.load(open(f"{A}/criteria.json"))
    labels = (("w0", "0 (v15conf, seeds 0--2)", "3"), ("w1", "1", "3"), ("w2", "2", "3"), ("w3", "3", "3"),
              ("pooled", "1--3 pooled", "9"))
    L = [r"\begin{tabular}{lccccccc}", r"\toprule",
         r" & & World I & \multicolumn{2}{c}{MWI} & Seeds, masks & & Clean AUROC \\",
         r"\cmidrule(lr){4-5}",
         r"Training assignment & Seeds & clean AUROC & logit & raw & resampled & $R(f_I)$ & $S - I$ \\", r"\midrule"]
    for key, label, n in labels:
        if key == "pooled":
            L.append(r"\midrule")
            sp = crit["D17_2_assignment_spread"]["spread"]
            lg, rw = sp["world seeds 1-3 (logit)"], sp["world seeds 1-3 (raw)"]
            L.append(f"1--3, mean (SD) & 3 $\\times$ 3 & & {lg['mean']:+.3f} ({lg['sd']:.3f}) & "
                     f"{rw['mean']:+.3f} ({rw['sd']:.3f}) & & & \\\\".replace("-", "$-$").replace("$-$$-$", "--"))
        e = eff[f"MWI ({key})"]
        sens = NUM.findall(eff[f"MWI ({key}), seeds and masks resampled (logit)"]["logit"])
        if key == "w0" and V16_SENS_W0:      # one canonical interval for this cell: the v16 analysis (Table 2, S18)
            sens = V16_SENS_W0
        gate = crit["G17_convergence"][key]["mean_clean_auroc_world_I"]
        L.append(f"{label} & {n} & {gate:.3f} & {r3(e['logit'])} & {r3(e['raw'])} & {r3(f'[{sens[1]}, {sens[2]}]')} & "
                 f"{r3(e['R_I'])} & {r3(e['clean_S_minus_I'])} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    with open("paper/tables/v17_assignments.tex", "w") as f:
        f.write("% generated by experiments/make_tables_v17.py from results/v17/analysis; do not edit\n" + "\n".join(L) + "\n")


def severities():
    sev = rows(f"{A}/assignment_severities.csv")
    L = [r"\begin{tabular}{llcccccc}", r"\toprule",
         r"World seed & World & $\bar\varepsilon$ non-SMM & $\bar\varepsilon$ SMM & difference & "
         r"AUROC($\varepsilon$) & AUROC(arm low-conf.\ fraction) & $n$ \\", r"\midrule"]
    for r in sev:
        d = float(r["eps_mean_pos"]) - float(r["eps_mean_neg"])
        L.append(f"{r['world_seed']} & {r['world']} & {float(r['eps_mean_neg']):.3f} & {float(r['eps_mean_pos']):.3f} & "
                 f"{d:+.3f} & {float(r['auc_eps']):.3f} & {float(r['auc_stat']):.3f} "
                 f"[{float(r['auc_stat_lo']):.3f}, {float(r['auc_stat_hi']):.3f}] & {int(r['n_neg']) + int(r['n_pos'])} \\\\"
                 .replace("-", "$-$"))
    L += [r"\bottomrule", r"\end{tabular}"]
    with open("paper/tables/v17_assignment_severities.tex", "w") as f:
        f.write("% generated by experiments/make_tables_v17.py from results/v17/analysis/assignment_severities.csv; do not edit\n"
                + "\n".join(L) + "\n")


def main():
    import os
    if os.path.exists(f"{A}/effects.csv"):
        assignments()
        print("wrote paper/tables/v17_assignments.tex")
    else:
        print(f"{A}/effects.csv absent (protocol v17 not yet analysed): v17_assignments.tex not written")
    severities()
    print("wrote paper/tables/v17_assignment_severities.tex")


if __name__ == "__main__":
    main()
