def files(prefix, world, mech, st, cell):
    d = {"v7": "results/v7/scores", "v8": "results/v7/scores", "v12": "results/v12/scores",
         "v13": "results/v13/scores", "v15conf": "results/v15conf/scores"}[prefix]
    out = sorted(glob.glob(f"{d}/{prefix}_{world}_w0_{mech}_{st}_{cell}_s*.csv"))
    assert len(out) == 3, (prefix, world, mech, st, cell, out)
    return out


class Store:
    def __init__(self, n_boot):
        self.n_boot, self.rs, self.cache = n_boot, None, {}

    def model(self, path):
        meta, sc = load_scores(path)
        if self.rs is None:
            self.rs = RowSet(meta["identifier"], [int(v) for v in meta["label"]], meta["child_id"], self.n_boot)
        return align(self.rs, meta["identifier"], meta["label"], sc)

    def auc(self, path, col):
        key = (path, col)
        if key not in self.cache:
            if path not in self.cache:
                self.cache[path] = self.model(path)
            self.cache[key] = self.rs.aucs(self.cache[path][col])
        return self.cache[key]

    def cells(self, prefix, mech, st, cell):
        """Bootstrap arrays (index 0 = point) for the four cells on both scales, clean per world,
        R_S, R_I, SE, raw SE, and per-seed SE points."""
        out = {}
        for w in ("S", "I"):
            fs = files(prefix, w, mech, st, cell)
            for pol in ("S", "I"):
                a = np.array([[self.auc(f, f"{mech}_{pol}_{st}_m{m}") for m in MASKS] for f in fs])
                out[f"m{w}{pol}"] = logit(a).mean(axis=(0, 1))
                out[f"auc{w}{pol}"] = a.mean(axis=(0, 1))
                out[f"seed{w}{pol}"] = logit(a[:, :, 0]).mean(axis=1)
                out[f"mask{w}{pol}"] = logit(a[:, :, 0]).mean(axis=0)
            out[f"clean{w}"] = np.mean([self.auc(f, "clean") for f in fs], axis=0)
        out["RS"] = out["mSS"] - out["mSI"]
        out["RI"] = out["mIS"] - out["mII"]
        out["SE"] = out["RS"] - out["RI"]
        out["SEraw"] = (out["aucSS"] - out["aucSI"]) - (out["aucIS"] - out["aucII"])
        out["cleanSI"] = out["cleanS"] - out["cleanI"]
        out["SE_seed"] = (out["seedSS"] - out["seedSI"]) - (out["seedIS"] - out["seedII"])
        out["SE_mask"] = (out["maskSS"] - out["maskSI"]) - (out["maskIS"] - out["maskII"])
        return out


def ci(arr):
    lo, hi = M.ci(arr[1:])
    return float(arr[0]), float(lo), float(hi)


def n(x, d=3):
    # a nonzero value that rounds to zero gets one more decimal so its sign stays visible
    if x != 0 and round(x, d) == 0:
        d += 1
    s = f"{x:+.{d}f}"
    return s.replace("-", "$-$")


def d3(sv):
    """Reprint an interval string at three decimals with typeset minus signs."""
    return re.sub(r"([+-]?\d+\.\d+)", lambda g: f"{float(g.group(1)):+.3f}", sv).replace("-", "$-$")


def nci(arr, d=3):
    p, lo, hi = ci(arr)
    return f"{n(p, d)} [{n(lo, d)}, {n(hi, d)}]"


def parse(s):
    v = [float(x) for x in re.findall(r"[+-]?\d+\.\d+", s)]
    return v


def check(name, mine, ref):
    assert abs(mine - ref) < TOL, (name, mine, ref)


def write(name, lines, src):
    with open(os.path.join(T, name), "w") as f:
        f.write(f"% generated by experiments/make_tables_v6.py from {src}; do not edit\n")
        f.write("\n".join(lines) + "\n")
    print("wrote", name)


