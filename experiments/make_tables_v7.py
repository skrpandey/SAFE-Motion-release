"""Paper tables for protocols v7 and v8 from results/v7/analysis. Run after analyze_v7.py.

Default: paper/tables/{planted_v7,remedies_v7,crossed_v7,real_v7}.tex; --masks writes the
mask-averaged {planted,remedies}_v7_masks.tex; --two-by-two writes two_by_two_v7.tex and .csv.
"""
import csv
import os
import re
from collections import defaultdict

A = "results/v7/analysis"
OUT = "paper/tables"
MECHS = ["runs", "whole", "frozen", "armruns"]
MECH_NAME = {"runs": "missing runs", "whole": "whole-joint absence", "frozen": "frozen frames",
             "armruns": "arm confidence"}
CELL_NAME = {"A_none": "none", "A_velocity": "velocity", "A_dropout": "whole-joint dropout",
             "A_both": "velocity + dropout", "B_coorddrop": "coordinate dropout"}
CELLS = ["A_none", "A_velocity", "A_dropout", "A_both", "B_coorddrop"]


def rows(name):
    with open(os.path.join(A, name)) as f:
        return list(csv.DictReader(f))


def num(x, d=3):
    s = f"{float(x):+.{d}f}"
    return s.replace("-", "$-$")


def ci(point, lo, hi, d=3):
    return f"{num(point, d)} [{num(lo, d)}, {num(hi, d)}]"


def parse_r(field):
    """'+0.7772 [+0.6382, +0.9365] sd_seeds ...' -> (point, lo, hi)."""
    m = re.match(r"\s*([+-][\d.]+) \[([+-][\d.]+), ([+-][\d.]+)\]", field or "")
    return tuple(float(v) for v in m.groups()) if m else None


def parse_auc(field):
    m = re.match(r"S ([\d.]+) I ([\d.]+)", field or "")
    return tuple(float(v) for v in m.groups()) if m else None


def clean_auc(field):
    return float(field.split()[0])


def group(g, **kw):
    hit = [r for r in g if all(r[k] == v for k, v in kw.items())]
    assert len(hit) == 1, (kw, len(hit))
    return hit[0]


def effect(e, proto, mech, strength, contrast):
    hit = [r for r in e if r["proto"] == proto and r["mechanism"] == mech
           and r["strength"] == strength and r["contrast"] == contrast]
    return hit[0] if hit else None


def proto_of(mech):
    return "v8" if mech in ("frozen", "armruns") else "v7"


def write(name, body):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w") as f:
        f.write("% generated by experiments/make_tables_v7.py from results/v7/analysis; do not edit\n")
        f.write(body)
    print("wrote", os.path.join(OUT, name))


def planted(g, e):
    lines = [r"\begin{tabular}{llcccccc}", r"\toprule",
             r"Mechanism & Strength & \multicolumn{2}{c}{AUC clean} & \R{}$(f_S)$ & \R{}$(f_I)$ & MWI & AUC$(f_S) - $AUC$(f_I)$ \\",
             r" & & $f_S$ & $f_I$ & & & & clean \\", r"\midrule"]
    for mech, strength in [("runs", "mid"), ("runs", "low"), ("whole", "mid"), ("frozen", "mid"), ("armruns", "mid")]:
        p = proto_of(mech)
        s = group(g, proto=p, mechanism=mech, strength=strength, world="S", cell="A_none", world_seed="0")
        i = group(g, proto=p, mechanism=mech, strength=strength, world="I", cell="A_none", world_seed="0")
        key = f"R_{mech}_{strength}_m2000"
        rs, ri = parse_r(s[key]), parse_r(i[key])
        se = effect(e, p, mech, strength, "SE(A_none)")
        cd = effect(e, p, mech, strength, "AUC_clean(f_S) - AUC_clean(f_I), A_none")
        lines.append(f"{MECH_NAME[mech]} & {strength} & {clean_auc(s['auc_clean']):.3f} & {clean_auc(i['auc_clean']):.3f} & "
                     f"{ci(*rs)} & {ci(*ri)} & {ci(se['point'], se['ci_lo'], se['ci_hi'])} & "
                     f"{ci(cd['point'], cd['ci_lo'], cd['ci_hi'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write("planted_v7.tex", "\n".join(lines))


def remedies(g, e):
    lines = [r"\begin{tabular}{llcccc}", r"\toprule",
             r"Mechanism & Remedy & \R{}$(f_S)$ & \R{}$(f_I)$ & Change in shortcut effect & Interaction (clean AUC) \\",
             r"\midrule"]
    for mech in MECHS:
        p = proto_of(mech)
        first = True
        for cell in CELLS:
            try:
                s = group(g, proto=p, mechanism=mech, strength="mid", world="S", cell=cell, world_seed="0")
                i = group(g, proto=p, mechanism=mech, strength="mid", world="I", cell=cell, world_seed="0")
            except AssertionError:
                continue
            key = f"R_{mech}_mid_m2000"
            rs, ri = parse_r(s[key]), parse_r(i[key])
            if cell == "A_none":
                d, it = "", ""
            else:
                c = effect(e, p, mech, "mid", f"SE({cell}) - SE(A_none)")
                x = effect(e, p, mech, "mid", f"interaction({cell}) gain_S - gain_I (clean AUC)")
                d = ci(c["point"], c["ci_lo"], c["ci_hi"])
                it = ci(x["point"], x["ci_lo"], x["ci_hi"])
            lab = MECH_NAME[mech] if first else ""
            first = False
            lines.append(f"{lab} & {CELL_NAME[cell]} & {num(rs[0])} & {num(ri[0])} & {d} & {it} \\\\")
        lines.append(r"\addlinespace")
    lines[-1:] = [r"\bottomrule", r"\end{tabular}", ""]
    write("remedies_v7.tex", "\n".join(lines))


def crossed(g):
    lines = [r"\begin{tabular}{l" + "c" * len(MECHS) + "}", r"\toprule",
             r"Trained against & " + " & ".join(f"tested: {MECH_NAME[m]}" for m in MECHS) + r" \\", r"\midrule"]
    for world in ["I", "S"]:
        lines.append(r"\multicolumn{%d}{l}{\emph{World %s models}} \\" % (len(MECHS) + 1, world))
        for tm in MECHS:
            r = group(g, proto=proto_of(tm), mechanism=tm, strength="mid", world=world, cell="A_none", world_seed="0")
            if tm == "armruns":           # corrected validity rule (protocol v13)
                r = v13_crossed(world)
            cells = []
            for te in MECHS:
                v = parse_r(r[f"R_{te}_mid_m2000"])
                txt = ci(*v)
                cells.append(r"\textbf{" + txt + "}" if te == tm else txt)
            lines.append(f"{MECH_NAME[tm]}" + ("$^{\\ast}$" if tm == "armruns" else "") + " & " + " & ".join(cells) + r" \\")
        for label, key in (("arm confidence$^{\\S}$ (nine seeds, corrected recipe)", "base9"),
                           ("arm confidence$^{\\S}$ (ST-GCN)", "A")):
            r = v16_crossed(world, key)
            if r is None:
                continue
            cells = []
            for te in MECHS:
                txt = ci(*parse_r(r[f"R_{te}_mid_m2000"]))
                cells.append(r"\textbf{" + txt + "}" if te == "armruns" else txt)
            lines.append(f"{label} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write("crossed_v7.tex", "\n".join(lines))


def v16_crossed(world, key):
    """Crossed responses of the current coordinate-rule confidence-only models (protocol v16: the
    nine-seed CompactCTRGCN cell "base9" and the ST-GCN cell "A"), first test mask, from
    results/v16/analysis/effects.csv; None when that analysis is absent (older trees)."""
    path = "results/v16/analysis/effects.csv"
    if not os.path.exists(path):
        return None
    out = {}
    for r in csv.DictReader(l for l in open(path) if not l.startswith("#")):
        m = re.match(r"crossed R under (\w+) \(mask 2000\), (\w+), World (\w)", r["quantity"])
        if m and m.group(2) == key and m.group(3) == world:
            out[f"R_{m.group(1)}_mid_m2000"] = r["logit"]
    if not out:
        return None
    assert len(out) == 4, out
    return out


def v13_crossed(world):
    """Crossed responses of the corrected-rule arm-confidence models (protocol v13), first test
    mask, from results/v13/analysis/effects.csv, in the groups.csv field format."""
    out = {}
    for r in csv.DictReader(open("results/v13/analysis/effects.csv")):
        m = re.match(r"crossed R under (\w+) \(mask 2000\)", r["contrast"])
        if m and r["proto"] == f"v13 vs v8, World {world}":
            out[f"R_{m.group(1)}_mid_m2000"] = r["logit"]
    assert len(out) == 4, out
    return out


def real(g):
    comp = rows("comparators.csv")
    gap = defaultdict(list)
    for r in comp:
        gap[r["cell"]].append(float(r["filtered_gap"]))
    lines = [r"\begin{tabular}{lcc" + "c" * len(MECHS) + "c}", r"\toprule",
             r"Model & AUC clean & QC gap & " + " & ".join(MECH_NAME[m] for m in MECHS) + r" & gapfill \\", r"\midrule"]
    for cell in CELLS:
        r = group(g, proto="v7", world="real", cell=cell)
        vals = [ci(*parse_r(r[f"R_{m}_mid_m2000"])) for m in MECHS]
        mg = sum(gap[cell]) / len(gap[cell])
        vals.append(ci(*parse_r(r["R_gapfill_mid_m2000"])))
        lines.append(f"{CELL_NAME[cell]} & {clean_auc(r['auc_clean']):.3f} & {num(mg)} & " + " & ".join(vals) + r" \\")
    lines.append(r"\midrule")
    ref = []
    for m in MECHS:
        i = group(g, proto=proto_of(m), mechanism=m, strength="mid", world="I", cell="A_none", world_seed="0")
        ref.append(ci(*parse_r(i[f"R_{m}_mid_m2000"])))
    lines.append(r"World I reference, own operator & & & " + " & ".join(ref) + r" & \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write("real_v7.tex", "\n".join(lines))




# mask-averaged tables
def _parse_ci(field):
    m = re.match(r"\s*([+-][\d.]+) \[([+-][\d.]+), ([+-][\d.]+)\]", field or "")
    return tuple(float(v) for v in m.groups()) if m else None


def planted_masks():
    g, e = rows("groups_masks.csv"), rows("effects_masks.csv")
    def grp(**kw):
        hit = [r for r in g if all(r[k] == v for k, v in kw.items())]
        assert len(hit) == 1, (kw, len(hit)); return hit[0]
    def eff(proto, mech, st, contrast):
        hit = [r for r in e if r["proto"] == proto and r["mechanism"] == mech and r["strength"] == st and r["contrast"] == contrast]
        return hit[0] if hit else None
    lines = [r"\begin{tabular}{llcccccc}", r"\toprule",
             r"Mechanism & Strength & \R{}$(f_S)$ & \R{}$(f_I)$ & MWI & Seed SD & Mask range & MWI, raw AUC \\",
             r"\midrule"]
    for mech, st in [("runs", "mid"), ("runs", "low"), ("whole", "mid"), ("frozen", "mid")]:   # arm confidence: armconf_v13_compare
        p = proto_of(mech)
        s_ = grp(proto=p, world="S", mechanism=mech, strength=st, cell="A_none")
        i_ = grp(proto=p, world="I", mechanism=mech, strength=st, cell="A_none")
        se = eff(p, mech, st, "SE(A_none)")
        lines.append(f"{MECH_NAME[mech]} & {st} & {ci(*_parse_ci(s_['R_maskmean']))} & {ci(*_parse_ci(i_['R_maskmean']))} & "
                     f"{ci(se['point'], se['ci_lo'], se['ci_hi'])} & {float(se['sd_seeds']):.3f} & {float(se['mask_range']):.3f} & "
                     f"{ci(se['raw_point'], se['raw_ci_lo'], se['raw_ci_hi'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write("planted_v7_masks.tex", "\n".join(lines))


def remedies_masks():
    e = rows("effects_masks.csv")
    def eff(proto, mech, contrast):
        hit = [r for r in e if r["proto"] == proto and r["mechanism"] == mech and r["strength"] == "mid" and r["contrast"] == contrast]
        return hit[0] if hit else None
    lines = [r"\begin{tabular}{llcccc}", r"\toprule",
             r"Mechanism & Remedy & MWI (mask mean) & Change vs.\ none, logit & Change vs.\ none, raw AUC & Seed SD \\",
             r"\midrule"]
    for mech in MECHS:
        p = proto_of(mech); first = True
        for cell in CELLS:
            se = eff(p, mech, f"SE({cell})")
            if se is None:
                continue
            if cell == "A_none":
                d1 = d2 = ""
            else:
                c = eff(p, mech, f"SE({cell}) - SE(A_none)")
                d1 = ci(c["point"], c["ci_lo"], c["ci_hi"]); d2 = ci(c["raw_point"], c["raw_ci_lo"], c["raw_ci_hi"])
            lab = MECH_NAME[mech] if first else ""; first = False
            lines.append(f"{lab} & {CELL_NAME[cell]} & {ci(se['point'], se['ci_lo'], se['ci_hi'])} & {d1} & {d2} & {float(se['sd_seeds']):.3f} \\\\")
        lines.append(r"\addlinespace")
    lines[-1:] = [r"\bottomrule", r"\end{tabular}", ""]
    write("remedies_v7_masks.tex", "\n".join(lines))


def two_by_two():
    """Post hoc: the four cells m(train world, test policy) per mechanism, averaged over the three
    test masks (logit AUROC, raw AUROC beside), the two responses and the interaction.
    Writes paper/tables/two_by_two_v7.tex and results/v7/analysis/two_by_two_v7.csv."""
    import csv as _csv
    import math
    g = rows("groups.csv"); e = rows("effects_masks.csv")
    lg = lambda a: math.log(a / (1 - a))
    specs = [("runs", "mid"), ("runs", "low"), ("whole", "mid"), ("frozen", "mid"), ("armruns", "mid")]
    lines = [r"\begin{tabular}{llcccccccc}", r"\toprule",
             r"Mechanism & Strength & $m(S,S)$ & $m(S,I)$ & $m(I,S)$ & $m(I,I)$ & $R(f_S)$ & $R(f_I)$ & SE & SE, raw AUROC \\", r"\midrule"]
    recs = []
    for mech, st in specs:
        p = proto_of(mech)
        cells = {}
        for w in ("S", "I"):
            r = group(g, proto=p, mechanism=mech, strength=st, world=w, cell="A_none", world_seed="0")
            aucs = [parse_auc(r[f"AUC_{mech}_{st}_m{m}"]) for m in (2000, 3000, 4000)]
            cells[w] = {"S": (sum(lg(a[0]) for a in aucs) / 3, sum(a[0] for a in aucs) / 3),
                        "I": (sum(lg(a[1]) for a in aucs) / 3, sum(a[1] for a in aucs) / 3)}
        rS = cells["S"]["S"][0] - cells["S"]["I"][0]; rI = cells["I"]["S"][0] - cells["I"]["I"][0]
        se = rS - rI; se_raw = (cells["S"]["S"][1] - cells["S"]["I"][1]) - (cells["I"]["S"][1] - cells["I"]["I"][1])
        ref = effect(e, p, mech, st, "SE(A_none)")
        recs.append({"mechanism": mech, "strength": st, "m_SS_logit": round(cells["S"]["S"][0], 4), "m_SI_logit": round(cells["S"]["I"][0], 4),
                     "m_IS_logit": round(cells["I"]["S"][0], 4), "m_II_logit": round(cells["I"]["I"][0], 4),
                     "m_SS_auc": round(cells["S"]["S"][1], 4), "m_SI_auc": round(cells["S"]["I"][1], 4),
                     "m_IS_auc": round(cells["I"]["S"][1], 4), "m_II_auc": round(cells["I"]["I"][1], 4),
                     "R_S": round(rS, 4), "R_I": round(rI, 4), "SE_logit": round(se, 4), "SE_raw": round(se_raw, 4),
                     "SE_effects_masks": ref["point"], "SE_raw_effects_masks": ref["raw_point"]})
        lines.append(f"{MECH_NAME[mech]} & {st} & " + " & ".join(
            f"{cells[w][pol][0]:.2f} ({cells[w][pol][1]:.3f})" for w, pol in (("S", "S"), ("S", "I"), ("I", "S"), ("I", "I")))
            + f" & {num(rS)} & {num(rI)} & {num(se)} & {num(se_raw)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write("two_by_two_v7.tex", "\n".join(lines))
    with open(os.path.join(A, "two_by_two_v7.csv"), "w") as f:
        w = _csv.DictWriter(f, fieldnames=list(recs[0])); w.writeheader(); w.writerows(recs)
    for r in recs:
        print(r["mechanism"], r["strength"], "SE", r["SE_logit"], "vs effects_masks", r["SE_effects_masks"], "| raw", r["SE_raw"], "vs", r["SE_raw_effects_masks"])


def length_probe():
    """Nested identifier-grouped length probes of the 15 real-split models (A minor 4 of the
    2026-11-11 reviews): per input configuration, the range over three seeds of the out-of-fold
    R^2 for log length from penultimate features (ridge and gradient boosting, raw and
    class-centred) and of the within-class score-length Spearman correlations, read from
    results/v7/analysis/length_inputs.csv (experiments/length_audit_inputs.py)."""
    path = os.path.join(A, "length_inputs.csv")
    if not os.path.exists(path):
        print("length_inputs.csv absent; length_probe.tex not written")
        return
    rs = [r for r in csv.DictReader(open(path)) if r["host"] == "asdpose_real"]
    assert len(rs) == 15, len(rs)
    names = {"A_none": "none", "A_velocity": "velocity", "A_dropout": "whole-joint dropout",
             "A_both": "velocity + dropout", "B_coorddrop": "coordinate dropout"}
    cols = (("r2_feats_ridge", "ridge"), ("r2_feats_ridge_within_class", "ridge, class-centred"),
            ("r2_feats_gb", "boosting"), ("r2_feats_gb_within_class", "boosting, class-centred"),
            ("spearman_neg", "Spearman, non-SMM"), ("spearman_pos", "Spearman, SMM"))
    rng = lambda v: f"{min(v):+.3f} to {max(v):+.3f}".replace("-", "$-$")
    lines = [r"\begin{tabular}{l" + "c" * len(cols) + "}", r"\toprule",
             r" & \multicolumn{4}{c}{Out-of-fold $R^2$, log length from penultimate features} & \multicolumn{2}{c}{Score-length correlation} \\",
             r"\cmidrule(lr){2-5}\cmidrule(lr){6-7}",
             "Input configuration & " + " & ".join(lab for _, lab in cols) + r" \\", r"\midrule"]
    for cell, lab in names.items():
        sub = [r for r in rs if r["model"].split("_real_")[1].rsplit("_s", 1)[0] == cell]
        assert len(sub) == 3, (cell, len(sub))
        lines.append(f"{lab} & " + " & ".join(rng([float(r[c]) for r in sub]) for c, _ in cols) + r" \\")
    lines.append(r"\midrule")
    lines.append("all 15 models & " + " & ".join(rng([float(r[c]) for r in rs]) for c, _ in cols) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write("length_probe.tex", "\n".join(lines))


