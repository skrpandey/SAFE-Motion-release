"""Paper tables for the v9 replication protocol from results/v9/analysis (same conventions as
experiments/make_tables_v7.py). Run after analyze_v9.py.

Writes paper/tables/{v9_gates,v9_verdicts,v9_effects,v9_crossed,v9_real,v9_null}.tex.
"""
import argparse
import csv
import json
import os
from collections import defaultdict

import numpy as np

MECH_NAME = {"runs": "missing runs", "whole": "whole-joint absence", "frozen": "frozen frames",
             "armruns": "arm confidence", "gapfill": "gap filling"}
HOST_NAME = {"mmasd_maracas": "MMASD maracas pair", "mmasd_chest_squat": "MMASD chest expansion vs squat",
             "utd_mhad_body_vs_arm": "UTD-MHAD whole-body vs arm", "utd_mhad_arm_only": "UTD-MHAD arm only"}
CELL_NAME = {"A_none": "none", "A_velocity": "velocity", "A_dropout": "whole-joint dropout",
             "A_both": "velocity + dropout", "B_coorddrop": "coordinate dropout"}
MECHS = ["runs", "whole", "frozen", "armruns"]


FULL = []  # full-precision values from criteria.json, used to undo the 4-dp rounding of the csv files


def refine(x):
    """Replace a 4-dp csv value by the unique full-precision criteria.json value it rounds from,
    so a value printed in two tables is rounded once from the same number."""
    v = float(x)
    if not (isinstance(x, str) and "." in x and len(x.split(".")[1]) == 4):
        return v
    hits = {f for f in FULL if round(f, 4) == round(v, 4)}
    return hits.pop() if len(hits) == 1 else v


def num(x, d=3):
    if x is None or x == "":
        return ""
    return f"{refine(x):+.{d}f}".replace("-", "$-$")


def pfmt(p, n_null):
    """Format a permutation p-value (1 + #null >= observed) / (n + 1); the minimum is printed as a floor."""
    if not p:
        return ""
    p = float(p)
    floor = 1.0 / (int(n_null) + 1)
    return f"1/{int(n_null) + 1} (floor)" if abs(p - floor) < 5e-4 else f"{p:.3f}"   # stored p has four decimals


def ci(point, lo, hi, d=3):
    return f"{num(point, d)} [{num(lo, d)}, {num(hi, d)}]"


def rows(a, name):
    with open(os.path.join(a, name)) as f:
        return list(csv.DictReader(f))


def write(out, name, body):
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, name), "w") as f:
        f.write("% generated by experiments/make_tables_v9.py from results/v9/analysis; do not edit\n")
        f.write(body)
    print("wrote", os.path.join(out, name))


def hosts_in(crit):
    return [h for h in crit.get("gates", {}) if h in HOST_NAME]


def gates(crit, out):
    lines = [r"\begin{tabular}{llcccl}", r"\toprule",
             r"Host & Gate & Clean AUC (out of fold) & Quality-only AUC & Length-only AUC & Outcome \\", r"\midrule"]
    for h, g in crit["gates"].items():
        if h not in HOST_NAME:
            continue
        rule = (f"$\\geq$ {g['clean_auc_min']:.2f}" if "clean_auc_min" in g else f"$\\leq$ {g['clean_auc_max']:.2f}")
        outcome = "passed" if g.get("clean_auc_pass") else "failed"
        lines.append(f"{HOST_NAME[h]} & {rule} & {g['clean_auc_oof']:.3f} ({g['n_subjects']} subjects, {g['n_clips']} clips) & "
                     f"{g['quality_only_auc_oof']:.3f} & {g['length_auc_oof']:.3f} & {outcome} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write(out, "v9_gates.tex", "\n".join(lines))


def verdicts(crit, out):
    hosts = [h for h in crit["replicates"] if h in HOST_NAME and crit["R1_se_positive"].get(h, {}).get("per_mechanism")]
    lines = [r"\begin{tabular}{l" + "l" * len(hosts) + "}", r"\toprule",
             "Rule & " + " & ".join(HOST_NAME[h] for h in hosts) + r" \\", r"\midrule"]

    def r1(h):
        pm = crit["R1_se_positive"][h]["per_mechanism"]
        parts = [f"{MECH_NAME[m]} {num(v['SE'][0])} [{num(v['SE'][1])}, {num(v['SE'][2])}], null p95 {num(v['null_p95'])}, "
                 f"{'passes' if v['pass'] else 'fails'}" for m, v in pm.items()]
        return ("\\textbf{fail}" if not crit["R1_se_positive"][h]["pass"] else "pass") + ": " + "; ".join(parts)

    def r2(h):
        v = crit["R2_scaling"].get(h, {})
        if v.get("pass") is None:
            return "n/a"
        return ("pass" if v["pass"] else "\\textbf{fail}") + f": {ci(*v['diff'])}"

    def r3(h):
        v = crit["R3_dropout_does_not_remove"][h]
        return ("pass (no reduction detected)" if v["pass"] else "\\textbf{fail}") + ": " + "; ".join(
            f"{MECH_NAME[m]} {ci(*x['diff'])}" for m, x in v["per_mechanism"].items())

    def asdpose_dropout_count():
        """Count ASDPose mechanisms where SE(A_dropout) - SE(A_none) (mask mean) has its lower
        interval end above zero; criteria.json holds the count at the time of protocol v9."""
        em = [r for r in csv.DictReader(open("results/v7/analysis/effects_masks.csv"))
              if r["contrast"] == "SE(A_dropout) - SE(A_none)" and r["strength"] == "mid"]
        return sum(float(r["ci_lo"]) > 0 for r in em), len(em)

    def r4(h):
        v = crit["R4_dropout_raises_somewhere"][h]
        k, n_ = asdpose_dropout_count()
        hist = v["asdpose_count"]
        cur = f"{k} of {n_}"
        return f"{v['count_raises']} of {v['n_mechanisms']} (ASDPose {cur}" + (f"; {hist} at the time of protocol v9)" if hist != cur else ")")

    def r5(h):
        v = crit["R5_reference"][h]
        return "; ".join(f"{MECH_NAME[m]} {num(x['R_I'])} [{num(x['R_I_ci'][0])}, {num(x['R_I_ci'][1])}]" for m, x in v.items())

    def r6(h):
        fl = [x for x in crit["R6_length"]["flagged"] if x.startswith(h + "/")]
        return f"{len(fl)} cells flagged" + ("" if not fl else " (\\textbf{fail})")

    def rep(h):
        return "\\textbf{no}" if not crit["replicates"][h] else "yes"

    for label, fn in (("R1: SE $>$ 0, above null, every mechanism", r1), ("R2: SE(mid) $-$ SE(low) $>$ 0", r2),
                      ("R3 (refutation rule): dropout interval not entirely below zero", r3), ("R4: pairs where dropout raises SE", r4),
                      ("R5: reference under own operator", r5), ("R6: length not exploited", r6),
                      ("Replicates (R1, R2, R3)", rep)):
        lines.append(f"{label} & " + " & ".join(r"\parbox[t]{0.38\textwidth}{\raggedright " + fn(h) + "}" for h in hosts) + r" \\[2pt]")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write(out, "v9_verdicts.tex", "\n".join(lines))


def effects(a, out):
    e = rows(a, "effects.csv")
    lines = [r"\begin{tabular}{llllcccccc}", r"\toprule",
             r"Host & Mechanism & Strength & Contrast & \R{}$(f_S)$ & \R{}$(f_I)$ & Value [95\% CI] & Null p95 & $p$ & Mask range \\",
             r"\midrule"]
    last = None
    for r in e:
        if r["host"] not in HOST_NAME or r["contrast"].startswith("interaction") or r["contrast"].startswith("AUC_clean"):
            continue
        hn = HOST_NAME[r["host"]] if r["host"] != last else ""
        last = r["host"]
        c = r["contrast"]
        for k, v in CELL_NAME.items():
            c = c.replace(f"SE({k}) - SE(A_none)", f"SE({v}) $-$ SE(none)")
        c = c.replace("SE(mid) - SE(low), A_none", "SE(mid) $-$ SE(low)").replace("SE(A_none)", "SE, none")
        c = c.replace("_", r"\_")
        lines.append(f"{hn} & {MECH_NAME.get(r['mechanism'], r['mechanism'])} & {r['strength']} & {c} & {num(r['R_S']) if r['R_S'] else ''} & "
                     f"{num(r['R_I']) if r['R_I'] else ''} & {ci(r['point'], r['ci_lo'], r['ci_hi'])} & "
                     f"{num(r['null_p95']) if r.get('null_p95') else ''} & {pfmt(r.get('null_p'), r.get('null_n') or 20)} & "
                     f"{r['mask_range'][:5] if r.get('mask_range') else ''} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write(out, "v9_effects.tex", "\n".join(lines))


def crossed(a, out):
    c = rows(a, "crossed.csv")
    hosts = sorted({r["host"] for r in c if r["host"] in HOST_NAME})
    lines = [r"\begin{tabular}{ll" + "c" * len(MECHS) + "}", r"\toprule",
             r"Host & Trained against & " + " & ".join(f"tested: {MECH_NAME[m]}" for m in MECHS) + r" \\", r"\midrule"]
    for h in hosts:
        for world in ("I", "S"):
            lines.append(r"\multicolumn{%d}{l}{\emph{%s, World %s models}} \\" % (len(MECHS) + 2, HOST_NAME[h], world))
            for tm in MECHS:
                rr = {r["test_mechanism"]: r for r in c if r["host"] == h and r["trained_world"] == world and r["trained_mechanism"] == tm}
                if not rr:
                    continue
                cells = []
                for te in MECHS:
                    if te in rr:
                        txt = ci(rr[te]["R"], rr[te]["ci_lo"], rr[te]["ci_hi"])
                        cells.append(r"\textbf{" + txt + "}" if te == tm else txt)
                    else:
                        cells.append("")
                lines.append(f" & {MECH_NAME[tm]} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write(out, "v9_crossed.tex", "\n".join(lines))


def real(a, out):
    r = rows(a, "real.csv")
    mechs = [m for m in MECHS + ["gapfill"] if any(x["mechanism_tested"] == m for x in r)]
    lines = [r"\begin{tabular}{ll" + "c" * len(mechs) + "}", r"\toprule",
             "Host & Model & " + " & ".join(MECH_NAME[m] for m in mechs) + r" \\", r"\midrule"]
    by = defaultdict(dict)
    for x in r:
        by[(x["host"], x["cell"])][x["mechanism_tested"]] = x
    for (h, cell), d in sorted(by.items()):
        vals = [ci(d[m]["R"], d[m]["ci_lo"], d[m]["ci_hi"]) + f" ({d[m]['subjects_opposite_sign']}/{d[m]['n_subjects']})" if m in d else "" for m in mechs]
        lines.append(f"{HOST_NAME.get(h, h)} & {CELL_NAME.get(cell, cell)} & " + " & ".join(vals) + r" \\")
    ref_hosts = sorted({h for h, _ in by})
    for h in ref_hosts:
        refs = []
        for m in mechs:
            x = next((z for z in r if z["host"] == h and z["mechanism_tested"] == m and z["reference_R_I"]), None)
            refs.append(num(x["reference_R_I"]) if x else "")
        lines.append(r"\midrule" + f"\n{HOST_NAME.get(h, h)} & World I reference & " + " & ".join(refs) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write(out, "v9_real.tex", "\n".join(lines))


def null(a, out):
    n = rows(a, "null.csv")
    e = {(r["host"], r["mechanism"], r["strength"]): r for r in rows(a, "effects.csv") if r["contrast"] == "SE(A_none)"}
    g = defaultdict(list)
    for r in n:
        g[(r["host"], r["mechanism"], r["strength"])].append(float(r["SE_perm"]))
    lines = [r"\begin{tabular}{llccccccc}", r"\toprule",
             r"Host & Mechanism & $n$ perms & Null mean & Null sd & Null 95th pct & Null max & Observed SE & $p$ \\", r"\midrule"]
    for k, v in sorted(g.items()):
        if k[0] not in HOST_NAME:
            continue
        x = e.get(k, {})
        lines.append(f"{HOST_NAME[k[0]]} & {MECH_NAME[k[1]]} & {len(v)} & {num(np.mean(v))} & {np.std(v, ddof=1):.3f} & "
                     f"{num(np.percentile(v, 95))} & {num(max(v))} & {num(x.get('point')) if x else ''} & {pfmt(x.get('null_p'), len(v))} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write(out, "v9_null.tex", "\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--analysis", default="results/v9/analysis")
    ap.add_argument("--out", default="paper/tables")
    args = ap.parse_args()
    crit = json.load(open(os.path.join(args.analysis, "criteria.json")))

    def collect(o):
        if isinstance(o, dict):
            for v in o.values():
                collect(v)
        elif isinstance(o, (list, tuple)):
            for v in o:
                collect(v)
        elif isinstance(o, float):
            FULL.append(o)
    collect(crit)
    gates(crit, args.out)
    verdicts(crit, args.out)
    effects(args.analysis, args.out)
    crossed(args.analysis, args.out)
    real(args.analysis, args.out)
    null(args.analysis, args.out)


if __name__ == "__main__":
    main()
