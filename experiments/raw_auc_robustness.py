"""Raw-AUC robustness check of the main v7 and v8 contrasts.

Recomputes SE per mechanism and SE(cell) - SE(A_none) on the raw scale (AUC_S - AUC_I) with the
paired child-clustered bootstrap of analyze_v7.py (shared resamples, seeds averaged inside
resamples, mask seed 2000), beside the logit values, and counts resample AUCs equal to 0 or 1
(where the logit clip at 1e-6 would act).
Writes results/v7/analysis/raw_auc_contrasts.csv and raw_auc_contrasts.md.
    conda run -n torch python experiments/raw_auc_robustness.py [--n-boot 2000]
"""
import argparse
import csv
import glob
import os
import re
import sys
from collections import defaultdict

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from safe_motion import metrics as M        # noqa: E402
from analyze_v7 import logit, RowSet        # noqa: E402

NAME_RE = re.compile(r"^(v[78])_(S|I)_w0_(runs|whole|frozen|armruns)_(mid|low)_([AB]_[a-z]+)_s(\d)\.csv$")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scores", default="results/v7/scores")
    ap.add_argument("--out", default="results/v7/analysis")
    ap.add_argument("--n-boot", type=int, default=2000)
    args = ap.parse_args()
    rs, A = None, {}
    for f in sorted(glob.glob(f"{args.scores}/v[78]_[SI]_w0_*.csv")):
        m = NAME_RE.match(os.path.basename(f))
        if not m:
            continue
        _, world, mech, st, cell, seed = m.groups()
        rd = list(csv.DictReader(open(f)))
        ids = [r["identifier"] for r in rd]
        if rs is None:
            rs = RowSet(ids, [int(r["label"]) for r in rd], [r["child_id"] for r in rd], args.n_boot)
        if set(ids) != set(rs.ids):
            continue
        order = np.array([rs.pos[i] for i in ids])
        for arm in ("S", "I"):
            c = f"{mech}_{arm}_{st}_m2000"
            A[(mech, st, world, cell, int(seed), arm)] = rs.aucs(np.array([float(r[c]) for r in rd])[order])
    n_boundary = sum(int(((a[1:] <= 0) | (a[1:] >= 1)).sum()) for a in A.values())
    amin, amax = min(a.min() for a in A.values()), max(a.max() for a in A.values())

    def R(mech, st, world, cell, scale):
        per = []
        for s in (0, 1, 2):
            k = (mech, st, world, cell, s)
            if k + ("S",) not in A:
                continue
            aS, aI = A[k + ("S",)], A[k + ("I",)]
            per.append((aS - aI) if scale == "raw" else (logit(aS) - logit(aI)))
        return np.mean(per, axis=0) if per else None

    rows = []
    for (mech, st) in sorted({(k[0], k[1]) for k in A}):
        cells = sorted({k[3] for k in A if k[0] == mech and k[1] == st})
        base = {sc: R(mech, st, "S", "A_none", sc) - R(mech, st, "I", "A_none", sc) for sc in ("raw", "logit")}
        rec = {"mechanism": mech, "strength": st, "contrast": "SE(A_none)"}
        for sc in ("raw", "logit"):
            ci = M.ci(base[sc][1:])
            rec.update({f"{sc}_point": base[sc][0], f"{sc}_ci_lo": ci[0], f"{sc}_ci_hi": ci[1],
                        f"{sc}_excludes_zero": bool(ci[0] > 0 or ci[1] < 0)})
        rows.append(rec)
        for cell in cells:
            if cell == "A_none":
                continue
            rec = {"mechanism": mech, "strength": st, "contrast": f"SE({cell}) - SE(A_none)"}
            for sc in ("raw", "logit"):
                d = (R(mech, st, "S", cell, sc) - R(mech, st, "I", cell, sc)) - base[sc]
                ci = M.ci(d[1:])
                rec.update({f"{sc}_point": d[0], f"{sc}_ci_lo": ci[0], f"{sc}_ci_hi": ci[1],
                            f"{sc}_excludes_zero": bool(ci[0] > 0 or ci[1] < 0)})
            rows.append(rec)
    os.makedirs(args.out, exist_ok=True)
    with open(f"{args.out}/raw_auc_contrasts.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        for r in rows:
            w.writerow({k: (f"{v:.4f}" if isinstance(v, float) else v) for k, v in r.items()})
    agree = sum(r["raw_excludes_zero"] == r["logit_excludes_zero"] for r in rows)
    lines = ["# Raw-AUC robustness of the v7 + v8 contrasts", "",
             "Generated by `experiments/raw_auc_robustness.py`. Same models, resamples and seed averaging as "
             "`analyze_v7.py`; mask seed 2000. Raw scale: AUC_S - AUC_I per model; SE and remedy contrasts as "
             "differences of those. A contrast 'excludes zero' when its 95% interval does.", "",
             "| mechanism | strength | contrast | raw [95% CI] | logit [95% CI] | both exclude zero |",
             "|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['mechanism']} | {r['strength']} | {r['contrast']} | {r['raw_point']:+.4f} [{r['raw_ci_lo']:+.4f}, {r['raw_ci_hi']:+.4f}] "
                     f"| {r['logit_point']:+.3f} [{r['logit_ci_lo']:+.3f}, {r['logit_ci_hi']:+.3f}] | "
                     f"{'yes' if r['raw_excludes_zero'] and r['logit_excludes_zero'] else ('neither' if not (r['raw_excludes_zero'] or r['logit_excludes_zero']) else ('raw only' if r['raw_excludes_zero'] else 'logit only'))} |")
    lines += ["", f"Agreement on 'excludes zero': {agree} of {len(rows)} contrasts.", "",
              "## Bootstrap boundary policy", "",
              f"The logit clips AUC at 1e-6 and 1 - 1e-6. Over {args.n_boot} child-clustered resamples of the "
              f"{len(rs.ids)} host test segments and {len(A)} (model, arm) score columns, the number of resample "
              f"AUCs equal to 0 or 1 is {n_boundary}; the smallest and largest resample AUC are {amin:.4f} and "
              f"{amax:.4f}. The clip is therefore never active on this host; if it were, the affected resamples "
              "would enter the percentile interval at the clipped value (not dropped), and the count would be reported.", ""]
    with open(f"{args.out}/raw_auc_contrasts.md", "w") as f:
        f.write("\n".join(lines))
    print("\n".join(lines[:12]))
    print(f"boundary AUCs: {n_boundary}; range {amin:.4f} to {amax:.4f}; wrote {args.out}/raw_auc_contrasts.csv")


if __name__ == "__main__":
    main()
