#!/bin/bash
# Regenerate every ASDPose-fit-dependent analysis, table and figure inside a shadow tree built by
# experiments/build_repair_view.py, from cleared targets, stopping at the first failure.
# Usage: bash experiments/run_release_pipeline.sh build/release_v14_clean
#   STOP_AFTER=preflight|clear  stops early (used by experiments/test_release_pipeline.sh)
set -euo pipefail
T=${1:?tree path}
cd "$T"
STOP_AFTER=${STOP_AFTER:-}
# every Python step runs through experiments/guarded_run.py, which enforces the output guard of
# safe_motion/paths.py on every write-mode open
PY="python3 -W ignore experiments/guarded_run.py"; PYT="conda run -n torch python -W ignore experiments/guarded_run.py"
REUSE_V11_FROM=${REUSE_V11_FROM:-}        # earlier tree (absolute path) whose v11 scores of the 30 real-split models are copied instead of rescored; needs the same checkpoints
mkdir -p pipeline_logs
die() { echo "FAIL: $*" >&2; exit 1; }
REGEN_FIGS="fig_interaction.pdf fig_interaction.svg fig_crossed_heatmap.pdf fig_crossed_heatmap.svg fig_oracle_mixture.pdf fig_oracle_mixture.svg
fig_remedies_forest.pdf fig_remedies_forest.svg fig_sample_size.pdf fig_sample_size.svg fig_null_v9.pdf fig_null_v9.svg
fig_qc_exclusion.pdf fig_qc_exclusion.svg forest_v7.pdf
forest_v7.png forest_v7.svg forest_v7_wide.pdf forest_v7_wide.png forest_v7_wide.svg v9_variability.pdf
v9_variability.png v9_variability.svg"
V11_KEEP="t1_t4_video_null.csv"        # fit-independent (tracking statistics only), slow to rebuild

count() { find "$1" -maxdepth 1 -name "$2" 2>/dev/null | wc -l; }

# preflight: tree layout, inputs, no stale or misnamed folders
[ -L experiments ] && [ -d paper ] && [ ! -L paper ] || die "not a shadow tree (experiments must be a link, paper a copy)"
case "$(pwd -P)" in *paper_pre_repair*) die "tree resolves into a backup folder";; esac
# output guard: every folder this driver writes must resolve outside the protected trees
python3 experiments/guarded_run.py --check . results results/v7/analysis results/v9/analysis results/v10/analysis \
  results/v11 results/v12/analysis results/v13/analysis results/v15conf/analysis results/v16/analysis results/v17/analysis results/provenance paper/tables paper/figures pipeline_logs \
  > pipeline_logs/guard_check.log 2>&1 || die "tree resolves into a protected tree (output guard; see pipeline_logs/guard_check.log)"
for d in results/v11/scoresmediapipe results/v11/featuresmediapipe; do
  [ ! -e "$d" ] || die "$d exists (wrong --tag); remove it"
done
[ -s results/v11/mediapipe_cache/index.csv ] || die "MediaPipe cache index missing"
EXT=$(python3 -c "import sys; sys.path.insert(0,'.'); from safe_motion.data import asdpose as D; print(D.SMM_ROOT)")/cache/external
[ -s "$EXT/index.csv" ] || die "RTMPose external cache index missing ($EXT)"
[ "$(count results/fits/v7/cache 'pilot_v7_real_*.pt')" -eq 15 ] || die "expected 15 repaired v7 real-split checkpoints"
[ "$(count results/fits/v10/cache 'pilot_v10_real_I_*.pt')" -eq 15 ] || die "expected 15 repaired v10 real-split checkpoints"
for p in v7 v10 v12 v13 v15conf v16; do [ "$(count results/$p/scores '*.csv')" -gt 0 ] || die "results/$p/scores empty"; done
[ "$(count results/v15conf/scores '*.csv')" -eq 12 ] || die "expected 12 v15conf score files"
[ "$(count results/v16/scores '*.csv')" -eq 24 ] || die "expected 24 v16 score files"
HAVE_V17=0; [ "$(count results/v17/scores '*.csv')" -eq 18 ] && HAVE_V17=1   # protocol v17 is optional until its fits exist
[ "$(count results/posthoc/conf_reliance/scores '*.csv')" -eq 18 ] || die "expected 18 confidence-reliance score files"
[ "$(count results/posthoc/adversary_probe '*.npz')" -eq 24 ] || die "expected 24 adversary-probe feature files"
echo "$(date +%T) preflight ok"
[ "$STOP_AFTER" = preflight ] && exit 0

# clear every target this driver writes, so a skipped step cannot leave an old file behind
CLEARED=pipeline_logs/cleared_tables.txt; : > $CLEARED
for f in paper/tables/*.tex; do [ "$(basename "$f")" = repair_v14.tex ] && continue        # cross-tree table (make_table_repair_compare.py), regenerated after both trees exist
  head -1 "$f" | grep -q "^% generated by" && { echo "$(basename "$f")" >> $CLEARED; rm "$f"; }; done
N_TABLES=$(wc -l < $CLEARED)
for f in $REGEN_FIGS; do rm -f "paper/figures/$f"; done
for d in scores features scores_mediapipe features_mediapipe dfr; do rm -f results/v11/$d/ours_*; done
find results/v11/analysis -maxdepth 1 -type f ! -name "$V11_KEEP" -delete
echo "$(date +%T) cleared $N_TABLES generated tables, $(echo $REGEN_FIGS | wc -w) figures, v11 outputs"
[ "$STOP_AFTER" = clear ] && exit 0

step() { local name=$1; shift; echo "$(date +%T) start $name"
  "$@" > pipeline_logs/$name.log 2>&1 || die "$name (see $T/pipeline_logs/$name.log)"; }
expect() { [ "$(count "$1" "$2")" -eq "$3" ] || die "expected $3 files $2 in $1, found $(count "$1" "$2")"; }

step analyze_v7          $PY experiments/analyze_v7.py
step analyze_v7_masks    $PY experiments/analyze_v7_masks.py
step analyze_v9_variance $PY experiments/analyze_v9_variance.py
step analyze_v10         $PY experiments/analyze_v10.py
step analyze_v12         $PY experiments/analyze_v12.py
step analyze_v13         $PY experiments/analyze_v13.py
python3 -c "import json,sys; sys.exit(not json.load(open('results/v13/analysis/criteria.json'))['V13_1_invariance'].get('pass'))" \
  || die "v13 invariance gate did not pass"
step analyze_v15conf     $PY experiments/analyze_v15conf.py --v15 results/v15conf --v13 results/v13
step conf_invariance_all $PY experiments/check_conf_invariance.py --valid-rule coords --all   # all segments, 3 masks, both paths
step analyze_v16         $PY experiments/analyze_v16.py --v16 results/v16 --v15 results/v15conf --epochs results/fits/v16bc/results/epochs --out results/v16/analysis
if [ -d results/v16/conf_reliance ]; then step conf_reliance_v16 $PY experiments/analyze_conf_reliance_v16.py; fi   # clean-selection scores only
if [ "$HAVE_V17" = 1 ]; then
  step analyze_v17         $PY experiments/analyze_v17.py --v17 results/v17 --v15 results/v15conf --epochs results/fits/v17/results/epochs --out results/v17/analysis
fi
step severities_v17      $PY experiments/assignment_severities_v17.py   # model-free: realized severities of the confidence-only worlds
step conf_reliance      $PY experiments/analyze_conf_reliance.py         # permutation reliance on the confidence channel (post hoc)
step natural_cue_checks $PY experiments/natural_cue_checks.py            # natural cue, person absence (post hoc)
step adversary_probe    $PY experiments/analyze_adversary_probe.py       # adversary diagnostic (post hoc)
step oracle_mixture      $PY experiments/oracle_mixture.py
step variance_v12        $PY experiments/variance_v12.py
step gap_table_b4        $PY experiments/gap_table_b4.py
step se_sample_size      $PY experiments/se_sample_size.py
step qc_gap_lengthproto  $PY experiments/qc_gap_lengthproto.py
step length_audit_inputs $PY experiments/length_audit_inputs.py --skip-v9
step variance_v7         $PY experiments/variance_v7.py                     # seed-and-mask sensitivity (post hoc)
step procedure_checks   $PY experiments/procedure_checks.py               # procedure-level intervals and checks (post hoc)
step null_display_v9     $PY experiments/null_display_v9.py                 # 20-draw nulls displayed, floor p
step cluster_scenarios   $PY experiments/cluster_scenarios_v7.py            # hypothetical test-cluster scenarios (post hoc)
step qc_exclusion        $PY experiments/qc_exclusion_report.py             # who the QC and length rules exclude
step natural_failures    $PY experiments/natural_failure_stats.py           # natural tracker-failure statistics
step holm_families       $PY experiments/holm_families.py                   # Holm within the two declared families (post hoc)
step repair_counts       $PY experiments/repair_counts.py                   # last-epoch and validation-row counts

t0=$(date +%s)
if [ -n "$REUSE_V11_FROM" ]; then
  # same repaired checkpoints (compared by resolved path), so the 30 models' scores are copied, not recomputed
  for proto in v7 v10; do
    diff <(for f in results/fits/$proto/cache/*.pt; do readlink -f "$f"; done | sort) \
         <(for f in "$REUSE_V11_FROM"/results/fits/$proto/cache/*.pt; do readlink -f "$f"; done | sort) > /dev/null \
      || die "REUSE_V11_FROM: $proto checkpoints differ from $REUSE_V11_FROM"
  done
  for d in scores scores_mediapipe features features_mediapipe; do cp "$REUSE_V11_FROM"/results/v11/$d/ours_* results/v11/$d/; done
  (cd "$REUSE_V11_FROM" && sha256sum results/v11/scores/ours_* results/v11/scores_mediapipe/ours_*) > pipeline_logs/v11_reused_from.sha256
  echo "$REUSE_V11_FROM" > pipeline_logs/v11_reused_from.txt
  echo "$(date +%T) v11 scores and features of our 30 models copied from $REUSE_V11_FROM (identical repaired checkpoints; hashes in pipeline_logs/v11_reused_from.sha256)"
  echo "$(date +%F),release/score_v11 ($(basename "$T"); copied from $(basename "$REUSE_V11_FROM"); no GPU),0.000" >> results/gpu_ledger.local.csv
else
  step score_v11_rtm       $PYT experiments/score_v11.py
  step score_v11_mp        $PYT experiments/score_v11.py --cache results/v11/mediapipe_cache --tag _mediapipe
  echo "$(date +%F),release/score_v11 ($(basename "$T")),$(python3 -c "print(f'{($(date +%s)-$t0)/3600:.3f}')")" >> results/gpu_ledger.local.csv
fi
for d in scores scores_mediapipe; do expect results/v11/$d 'ours_*.csv' 30; expect results/v11/$d '*.csv' 49; done
for d in features features_mediapipe; do expect results/v11/$d 'ours_*.npz' 30; expect results/v11/$d '*.npz' 49; done
step dfr_v11             $PY experiments/within_set_v11.py --skip-training
expect results/v11/dfr '*.csv' 49
step analyze_v11         $PY experiments/analyze_v11.py --skip-sheets
step calibration_v5      $PY experiments/calibration_v5.py
step check_platt_slopes  $PY experiments/check_platt_slopes.py
step summary_numbers_v11 $PY experiments/summary_numbers_v11.py
step t9_worst_case       $PY experiments/t9_worst_case.py
step t9_finish           $PY experiments/t9_finish.py
python3 -c "import json,sys; s=json.load(open('results/v11/analysis/criteria.json'))['T9']['status']; sys.exit('pending' in s)" \
  || die "criteria.json T9 still pending (t9_finish did not update it)"

step make_tables_v7      $PY experiments/make_tables_v7.py
step make_tables_v7_masks $PY experiments/make_tables_v7.py --masks          # planted_v7_masks, remedies_v7_masks (Table S11)
step make_tables_v7_2x2  $PY experiments/make_tables_v7.py --two-by-two     # two_by_two_v7
step make_tables_v9      $PY experiments/make_tables_v9.py
step make_tables_v10     $PY experiments/make_tables_v10.py
step make_tables_v11     $PY experiments/make_tables_v11.py
step make_tables_v13     $PY experiments/make_tables_v13.py
step make_tables_v15conf $PY experiments/make_tables_v15conf.py --analysis results/v15conf/analysis
step make_tables_v12     $PY experiments/make_tables_v12.py
step make_tables_v6      $PY experiments/make_tables_v6.py
step make_tables_v16     $PY experiments/make_tables_v16.py            # after v6: confonly_main reads cells_v6.csv and planted_v6.tex
step make_tables_v17     $PY experiments/make_tables_v17.py            # severity table always; assignment table when v17 exists
step fig_interaction    $PY experiments/fig_interaction.py              # interaction plot from cells_v6.csv
step make_tables_repair  $PY experiments/make_tables_repair.py
step split_tables_v6     $PY experiments/split_tables_v6.py
step rename_tables_mwi   $PY experiments/rename_tables_mwi.py
step fig_forest          $PY experiments/fig_forest.py
step fig_heatmap_forest  $PY experiments/fig_heatmap_forest.py

# every cleared target must exist again
while read -r t; do [ -s "paper/tables/$t" ] || die "table $t was cleared but not regenerated"; done < $CLEARED
n=0; for f in paper/tables/*.tex; do head -1 "$f" | grep -q "^% generated by" && n=$((n+1)); done
echo "$(date +%T) regenerated all $N_TABLES cleared tables ($n generated tables present)"
for f in $REGEN_FIGS; do [ -s "paper/figures/$f" ] || die "figure $f not regenerated"; done
! grep -l "Shortcut effect\|shortcut effect" paper/tables/*.tex || die "a generated table still says shortcut effect"
step model_provenance    $PY experiments/model_provenance.py --tree .   # provenance map of every final model (review B, M5)
( sha256sum paper/tables/*.tex; cd paper/figures && sha256sum $REGEN_FIGS | sed 's|  |  paper/figures/|' ) > MANIFEST.sha256
N_DEF=$(grep -c '^ *step ' experiments/run_release_pipeline.sh); N_RUN=$(ls pipeline_logs/*.log | grep -v "guard_check" | wc -l)
echo "$(date +%T) PIPELINE_DONE ($n tables, $(echo $REGEN_FIGS | wc -w) figures; $N_RUN of $N_DEF defined steps ran$([ -n "$REUSE_V11_FROM" ] && echo ", 2 score_v11 steps replaced by the copy from $(basename "$REUSE_V11_FROM")"); manifest $T/MANIFEST.sha256)"
