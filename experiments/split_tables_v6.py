"""Split dense generated tables into narrower supplement tables. No number is recomputed: every
cell is copied from the source table named in each output header, so rerun after its generator.

  real_v7.tex        -> real_v7_a.tex, real_v7_b.tex
  real_ref_v10.tex   -> real_ref_v10_rows.tex (original, reference, difference rows)
  v9_effects.tex     -> v9_effects_mmasd.tex, v9_effects_utd.tex
  v11_transfer_full  -> v11_transfer_overall.tex, v11_transfer_category.tex
    python experiments/split_tables_v6.py
"""
import os
import re

T = "paper/tables"


def read(name):
    lines = open(os.path.join(T, name)).read().splitlines()
    head = next(l for l in lines if " & " in l and l.rstrip().endswith("\\\\"))
    body, rule = [], []
    for l in lines[lines.index(head) + 1:]:
        if l.startswith("\\midrule") and body:
            rule.append(len(body))
        if " & " in l and l.rstrip().endswith("\\\\"):
            body.append(cells(l))
    return cells(head), body, rule


def cells(line):
    return [c.strip() for c in re.split(r"(?<!\\)&", line.rstrip()[:-2])]


def write(name, src, spec, header, rows, mids=()):
    out = [f"% generated by experiments/split_tables_v6.py from paper/tables/{src}; do not edit",
           f"\\begin{{tabular}}{{{spec}}}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule"]
    for k, r in enumerate(rows):
        if k in mids:
            out.append("\\midrule")
        out.append(" & ".join(r) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    open(os.path.join(T, name), "w").write("\n".join(out) + "\n")
    print("wrote", name)


def cols(header, body, keep):
    return [header[i] for i in keep], [[r[i] if i < len(r) else "" for i in keep] for r in body]


def main():
    h, b, mids = read("real_v7.tex")
    hh, bb = cols(h, b, [0, 1, 2, 3, 4])
    write("real_v7_a.tex", "real_v7.tex", "lcccc", hh, bb, mids)
    hh, bb = cols(h, b, [0, 5, 7])          # arm confidence (column 6) used the original validity rule; not shown
    write("real_v7_b.tex", "real_v7.tex", "lcc", hh, bb, mids)

    h, b, _ = read("real_ref_v10.tex")
    rows = []
    for r in b:
        parts = [re.match(r"(.+?) / (.+?) / (.+)$", c).groups() for c in r[1:]]
        rows.append([r[0], "original"] + [p[0] for p in parts])
        rows.append(["", "reference"] + [p[1] for p in parts])
        rows.append(["", "difference"] + [p[2] for p in parts])
    out_rows, mids = [], []
    for k, r in enumerate(rows):
        if k and k % 3 == 0:
            mids.append(k)
        out_rows.append(r)
    write("real_ref_v10_rows.tex", "real_ref_v10.tex", "ll" + "c" * (len(h) - 1), [h[0], ""] + h[1:], out_rows, mids)

    h, b, _ = read("v9_effects.tex")
    groups, cur = {}, None
    for r in b:
        if r[0]:
            cur = r[0]
        groups.setdefault(cur, []).append(r[1:])
    for host, name in (("MMASD chest expansion vs squat", "v9_effects_mmasd.tex"),
                       ("UTD-MHAD whole-body vs arm", "v9_effects_utd.tex")):
        rows = groups[host]
        for k in range(len(rows) - 1, 0, -1):          # blank repeated mechanism names
            if rows[k][0] == rows[k - 1][0]:
                rows[k] = [""] + rows[k][1:]
        rows = [[rows[k][0]] + rows[k][1:] for k in range(len(rows))]
        write(name, "v9_effects.tex", "lllcccccc", h[1:], rows)

    h, b, _ = read("v11_transfer_full.tex")
    hh, bb = cols(h, b, [0, 1, 2, 7, 8])
    write("v11_transfer_overall.tex", "v11_transfer_full.tex", "lcccc", hh, bb)
    hh, bb = cols(h, b, [0, 3, 4, 5, 6])
    write("v11_transfer_category.tex", "v11_transfer_full.tex", "lcccc", hh, bb)


if __name__ == "__main__":
    main()
